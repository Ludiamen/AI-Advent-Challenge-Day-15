#!/usr/bin/env bash
# Практическая проверка задания Дня 12: как пользователь настраивает агента под
# себя и что от этого меняется в ответах.
#
# Имена переменных латиницей: bash не поддерживает кириллицу в идентификаторах
# и молча превращает $ИМЯ в обычный текст.
#
# Запуск:  bash демо.sh  [путь-к-python]
set -u
PY="${1:-python3}"
MEM="демо-память"
VOPROS="Что нужно сделать, чтобы перенести справочник организаций из схемы gissys?"

step() { printf '\n\n=== %s ===\n' "$1"; }

rm -rf "$MEM"

step "1. ГОТОВЫЕ ПРОФИЛИ: четыре роли, которые встречаются в проекте"
"$PY" cli.py --память-в "$MEM" --заготовки

step "2. ПРОФИЛЬ ИНЖЕНЕРА: что настраивает пользователь и что проверяется кодом"
"$PY" cli.py --память-в "$MEM" --кто инженер --профиль

step "3. ОДИН ВОПРОС ДВУМ ПОЛЬЗОВАТЕЛЯМ: инженер"
"$PY" cli.py --память-в "$MEM" --кто инженер --маршрутизатор выкл "$VOPROS"

step "4. ТОТ ЖЕ ВОПРОС: менеджер (без кода, таблицами, по имени и на «вы»)"
"$PY" cli.py --память-в "$MEM" --кто менеджер --маршрутизатор выкл --трейс "$VOPROS"

step "5. ПРАВКА ОДНОГО ПРЕДПОЧТЕНИЯ НА ЛЕТУ"
"$PY" cli.py --память-в "$MEM" --кто менеджер --настройка формат/структура=проза
"$PY" cli.py --память-в "$MEM" --кто менеджер --настройка формат/длина=моментально 2>&1 | tail -2

step "6. СЦЕНАРИИ: во что превращается запрос пользователя"
"$PY" cli.py --память-в "$MEM" --кто тимлид --сценарии

step "7. ЗАПРОС С ТРИГГЕРОМ: сценарий запускается сам"
"$PY" cli.py --память-в "$MEM" --кто тимлид --маршрутизатор выкл \
  "Оцени задачу: показать на карте участки, отключённые закрытой арматурой"

step "8. ЧТО ОСТАЛОСЬ В ПАМЯТИ ПОСЛЕ СЦЕНАРИЯ"
"$PY" cli.py --память-в "$MEM" --кто тимлид --память
"$PY" cli.py --память-в "$MEM" --кто тимлид --решения | head -12

step "9. СОСТОЯНИЕ ЗАДАЧИ: этап, шаг и ожидаемое действие"
"$PY" cli.py --память-в "$MEM" --кто тимлид --новая-задача разбор --название "разбор состояния"
"$PY" cli.py --память-в "$MEM" --кто тимлид --задача разбор --состояние

step "10. ПАУЗА НА ЛЮБОМ ЭТАПЕ: флаг поверх этапа, а не пятая стадия"
"$PY" cli.py --память-в "$MEM" --кто тимлид --задача разбор --пауза
"$PY" cli.py --память-в "$MEM" --кто тимлид --задача разбор --состояние | head -8

step "11. ПРЫЖОК ЧЕРЕЗ ЭТАП: стрелки нет, и код называет законный маршрут"
# Задача тут на паузе — и это ничего не меняет: пауза живёт поверх стадии,
# а переход всё равно проверяют ворота.
"$PY" cli.py --память-в "$MEM" --кто тимлид --задача разбор --стадия done 2>&1 | head -12

step "12. УСЛОВИЯ ПЕРЕХОДА: базовые в коде, личные — под свой процесс"
"$PY" cli.py --память-в "$MEM" --кто тимлид --условия | head -20

step "13. РЕАЛИЗАЦИЯ БЕЗ УТВЕРЖДЁННОГО ПЛАНА: стрелка есть, условие — нет"
"$PY" cli.py --память-в "$MEM" --кто тимлид --задача разбор --стадия execution 2>&1 | head -8

step "14. КУДА МОЖНО И ЧТО МЕШАЕТ ОСТАЛЬНОМУ"
"$PY" cli.py --память-в "$MEM" --кто тимлид --задача разбор --переходы

step "15. СВОЁ УСЛОВИЕ: пользователь ужесточает жизненный цикл под себя"
"$PY" cli.py --память-в "$MEM" --кто тимлид --условие нужна-ссылка \
     --откуда validation --куда done --проверка есть-в-собранном \
     --значение репозиторий \
     --правило "В готово — только со ссылкой на репозиторий" \
     --почему "иначе итог задачи невозможно найти через месяц"
"$PY" cli.py --память-в "$MEM" --кто тимлид --условия | tail -12

step "16. НОВЫЙ ПОЛЬЗОВАТЕЛЬ: профиль пуст, мастер настройки ещё не проходили"
"$PY" cli.py --память-в "$MEM" --кто стажёр --профиль | head -6

printf '\n\nГотово. Память прогона осталась в «%s» — её можно посмотреть глазами.\n' "$MEM"
printf 'Профили лежат порознь: %s/долго/<кто>/профиль.json\n' "$MEM"
