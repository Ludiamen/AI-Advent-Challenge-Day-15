def тест_сценарий(корень: str, имя_сценария: str = "оцени задачу") -> dict[str, Any]:
    """Прогон пользовательского сценария: кто, в каком порядке и что сделал."""
    запрос = ЗАПРОСЫ_СЦЕНАРИЕВ.get(имя_сценария, ЗАПРОС_ПО_УМОЛЧАНИЮ)
    print(f"\n{LINE}\n6. СЦЕНАРИЙ «{имя_сценария}»\n{LINE}")
    print(f"Запрос: {запрос}\n")
    рабочий = агент(f"{корень}/сценарий")
    try:
        рабочий.use_template("тимлид")

        def шаг(шг, номер, всего):
            print(f"  [{номер}/{всего}] {шг.агент:<14} {шг.стадия:<11} {шг.model_key}",
                  flush=True)

        прогон = рабочий.run_scenario(запрос, name=имя_сценария, on_step=шаг)
    except AgentError as exc:
        print(f"  сценарий не отработал: {exc}")
        return {"название": f"6. Сценарий «{имя_сценария}»", "ошибка": str(exc)}
    finally:
        рабочий.close()

    print(f"\n  шагов {len(прогон.шаги)}, токенов {tokens.format_tokens(прогон.токенов)}, "
          f"{tokens.format_cost(прогон.стоимость)}")
    return {
        "название": f"6. Сценарий «{имя_сценария}»",
        "запрос": запрос,
        "прогон": прогон.to_dict(),
    }


