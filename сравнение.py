def тест_модели(ключи: list[str]) -> dict[str, Any]:
    """Прогоняет одни и те же задания на разных моделях — проверка распределения ролей.

    Ярлык «сильная модель» ничего не гарантирует на конкретной задаче, поэтому
    распределение из каталога стоит подтверждать замером, а не принимать на веру.
    """
    from agent.llm import Client, LLMError

    print(f"\n{LINE}\n5. МОДЕЛИ: одна работа на разных моделях\n{LINE}")
    # Тайм-аут здесь короче рабочего (120 с) намеренно. В сравнении важно, чтобы
    # одна неотвечающая модель попала в отчёт строкой «ошибка», а не остановила
    # прогон: провайдер может молчать минутами, и умножение на число моделей
    # превращает замер в ожидание.
    клиент = Client(temperature=0.0, timeout=МОДЕЛЬНЫЙ_ТАЙМАУТ)
    итог: dict[str, Any] = {"название": "5. Сравнение моделей", "задания": []}
    try:
        for задание in ЗАДАНИЯ_МОДЕЛЕЙ:
            print(f"\nЗадание: {задание['имя']} (ждём в ответе «{задание['ожидание']}»)")
            строки = []
            for ключ in ключи:
                описание = catalog.get(ключ)
                if not описание.has_key:
                    print(f"  {ключ:<14} ключа нет, пропуск")
                    continue
                try:
                    ответ = клиент.call(ключ, задание["сообщения"],
                                        max_tokens=задание["токенов"], temperature=0.0,
                                        low_effort=задание["низкое_усилие"])
                except LLMError as exc:
                    print(f"  {ключ:<14} ошибка: {str(exc)[:60]}")
                    строки.append({"модель": ключ, "ошибка": str(exc)[:120]})
                    continue
                попал = задание["ожидание"].lower() in ответ.text.lower()
                строки.append({
                    "модель": ключ,
                    "бесплатно": описание.free,
                    "попал": попал,
                    "секунд": round(ответ.elapsed, 1),
                    "токенов": ответ.total_tokens,
                    "стоимость": ответ.cost,
                    "ответ": ответ.text[:400],
                })
                print(f"  {ключ:<14} {'попал' if попал else 'мимо':<6} "
                      f"{ответ.elapsed:>5.1f} с  {tokens.format_tokens(ответ.total_tokens):>6} т.  "
                      f"{tokens.format_cost(ответ.cost)}")
            итог["задания"].append({"имя": задание["имя"], "ожидание": задание["ожидание"],
                                    "строки": строки})
    finally:
        клиент.close()
    return итог


# --- отчёт --------------------------------------------------------------------

def отчёт(результаты: list[dict[str, Any]], модели: dict[str, Any] | None, путь: str) -> None:
    части = ["# Результаты прогона аблации слоёв памяти", ""]
    части.append("Каждая проверка — один и тот же вопрос при разном наборе включённых слоёв.")
    части.append("Прогон живой, на реальных ключах; ответы приведены как есть.")
    части.append("")

    for итог in результаты:
        части.append(f"## {итог['название']}")
        части.append("")

        if "профили" in итог:
            части.append(f"**Вопрос:** {итог['вопрос']}")
            части.append("")
            имена = [п["имя"] for п in итог["профили"]]
            признаки = list(итог["профили"][0]["признаки"]) if итог["профили"] else []
            части.append("| признак | " + " | ".join(имена) + " |")
            части.append("|---|" + "---|" * len(имена))
            for признак in признаки:
                клетки = " | ".join(str(п["признаки"][признак]) for п in итог["профили"])
                части.append(f"| {признак} | {клетки} |")
            части.append("")
            for профиль in итог["профили"]:
                части.append(f"### [{профиль['имя']}] {профиль['сводка']}")
                части.append("")
                части.append("```")
                части.append(профиль["текст"][:1800].strip())
                части.append("```")
                if профиль["расхождения"]:
                    части.append("")
                    части.append(f"Расхождений с профилем: {len(профиль['расхождения'])} "
                                 f"(попыток {профиль['попыток']}).")
                части.append("")
            continue

        if "прогон" in итог:
            прогон = итог["прогон"]
            части.append(f"**Запрос:** {итог['запрос']}")
            части.append("")
            части.append(f"Задача `{прогон['task_id']}`, шагов {len(прогон['шаги'])}, "
                         f"токенов {прогон['токенов']}.")
            части.append("")
            части.append("| шаг | агент | стадия | модель | токенов |")
            части.append("|---|---|---|---|---|")
            for номер, шаг in enumerate(прогон["шаги"], 1):
                части.append(f"| {номер} | {шаг['агент']} | {шаг['стадия']} "
                             f"| {шаг['модель']} | {шаг['токенов']} |")
            части.append("")
            for номер, шаг in enumerate(прогон["шаги"], 1):
                кому = "ответ пользователю" if номер == len(прогон["шаги"]) else "вход следующего шага"
                части.append(f"### Шаг {номер}: {шаг['агент']} ({кому})")
                части.append("")
                части.append("```")
                части.append(шаг["текст"][:1500].strip())
                части.append("```")
                части.append("")
            if прогон.get("решение"):
                части.append(f"**В журнал решений:** {прогон['решение']['заголовок']}")
                части.append("")
            continue

        if итог.get("ошибка"):
            части.append(f"Прогон не состоялся: {итог['ошибка']}")
            части.append("")
            continue

        if итог.get("пояснение"):
            части.append(итог["пояснение"])
            части.append("")
        части.append(f"**Вопрос:** {итог['вопрос']}")
        части.append("")
        имена = [в["имя"] for в in итог["варианты"]]
        части.append("| признак в ответе | " + " | ".join(имена) + " |")
        части.append("|---|" + "---|" * len(имена))
        for маркер in МАРКЕРЫ:
            клетки = " | ".join("да" if в["признаки"][маркер] else "—" for в in итог["варианты"])
            части.append(f"| {маркер} | {клетки} |")
        части.append("| токенов в запросе | " + " | ".join(
            str(sum(с["токенов"] for с in в["слои_промпта"].values())) for в in итог["варианты"]
        ) + " |")
        части.append("")
        for вариант in итог["варианты"]:
            части.append(f"### [{вариант['имя']}] слои: {', '.join(вариант['слои']) or 'ни одного'}")
            части.append("")
            части.append("```")
            части.append(вариант["текст"][:1800].strip())
            части.append("```")
            части.append("")

    if модели:
        части.append("## 5. Сравнение моделей")
        части.append("")
        for задание in модели["задания"]:
            части.append(f"### {задание['имя']} (ждём «{задание['ожидание']}»)")
            части.append("")
            части.append("| модель | тариф | результат | секунд | токенов | стоимость |")
            части.append("|---|---|---|---|---|---|")
            for строка in задание["строки"]:
                if "ошибка" in строка:
                    части.append(f"| {строка['модель']} | — | ошибка: {строка['ошибка']} | | | |")
                    continue
                части.append(
                    f"| {строка['модель']} | {'бесплатно' if строка['бесплатно'] else 'платно'} "
                    f"| {'попал' if строка['попал'] else 'мимо'} | {строка['секунд']} "
                    f"| {строка['токенов']} | {tokens.format_cost(строка['стоимость'])} |"
                )
            части.append("")
            # Вердикт «мимо» сам по себе ничего не объясняет: разницу между
            # «модель не поняла задачу» и «ответ обрезан бюджетом» видно только
            # в самом ответе.
            части.append("<details><summary>что ответили</summary>")
            части.append("")
            for строка in задание["строки"]:
                if "ошибка" in строка:
                    continue
                отрывок = строка["ответ"].strip().replace("\n", " ")[:220]
                части.append(f"* **{строка['модель']}** — `{отрывок}`")
            части.append("")
            части.append("</details>")
            части.append("")

    with open(путь, "w", encoding="utf-8") as файл:
        файл.write("\n".join(части) + "\n")
    print(f"\nОтчёт записан: {путь}")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Аблация слоёв памяти: один вопрос, разный набор слоёв.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--тест", dest="test", type=int, default=0, choices=[0, 1, 2, 3, 4],
                        help="прогнать одну проверку (1-4); 0 — все")
    parser.add_argument("--профили", dest="profiles", action="store_true",
                        help="один вопрос через все заготовки профилей")
    parser.add_argument("--сценарий", dest="scenario", default="", metavar="ИМЯ",
                        nargs="?", const="оцени задачу",
                        help="прогнать пользовательский сценарий (по умолчанию «оцени задачу»)")
    parser.add_argument("--модели", dest="models", action="store_true",
                        help="сравнить модели на заданиях проекта")
    parser.add_argument("--только-модели", dest="only_models", action="store_true",
                        help="пропустить аблацию и прогнать одно сравнение моделей")
    parser.add_argument("--платные", dest="paid", action="store_true",
                        help="включить в сравнение моделей платные ds-flash и ds-pro")
    parser.add_argument("--в", dest="out", default="", metavar="ПУТЬ",
                        help="записать отчёт в файл (например, RESULTS.md)")
    parser.add_argument("--подробно", action="store_true",
                        help="печатать ответы целиком")
    аргументы = parser.parse_args()

    проверки = {1: тест_профиль, 2: тест_рабочая, 3: тест_короткая, 4: тест_инварианты}
    # Персонализация и сценарии — это про День 12, аблация слоёв — про День 11.
    # Когда просят проверить что-то одно, остальное гонять незачем: каждый
    # прогон стоит токенов и упирается в минутный лимит провайдера.
    точечно = bool(аргументы.profiles or аргументы.scenario or аргументы.only_models)
    if аргументы.only_models:
        выбранные, аргументы.models = [], True
    elif точечно:
        выбранные = []
    else:
        выбранные = [аргументы.test] if аргументы.test else list(проверки)

    корень = tempfile.mkdtemp(prefix="аблация-")
    результаты: list[dict[str, Any]] = []
    сравнение_моделей: dict[str, Any] | None = None
    try:
        for номер in выбранные:
            try:
                итог = проверки[номер](корень)
            except AgentError as exc:
                print(f"Проверка {номер} не прошла: {exc}", file=sys.stderr)
                continue
            напечатать(итог)
            результаты.append(итог)

        if аргументы.profiles:
            профили_итог = тест_профили(корень, list(interview.TEMPLATES))
            напечатать_профили(профили_итог)
            результаты.append(профили_итог)

        if аргументы.scenario:
            результаты.append(тест_сценарий(корень, аргументы.scenario))

        if аргументы.models:
            ключи = ["groq-allam7b", "groq-20b", "groq-120b", "glm-flash"]
            if аргументы.paid:
                ключи += ["ds-flash", "ds-pro"]
            сравнение_моделей = тест_модели(ключи)
    finally:
        shutil.rmtree(корень, ignore_errors=True)

    if аргументы.out:
        отчёт(результаты, сравнение_моделей, аргументы.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
