#!/usr/bin/env python3
"""Проверка задания Дня 13: пауза на любом этапе и продолжение без повторов.

Прогон устроен так, чтобы доказать главное, а не показать красивый вывод.
Доказывать нужно две вещи:

  1. Задачу можно остановить на каждом этапе — и остановка не теряет сделанного.
  2. Продолжение НЕ переигрывает пройденное: ни повторных вызовов модели, ни
     повторных вопросов человеку.

Второе проверяется честно: между паузой и продолжением процесс завершается
полностью. Новый запуск ничего не знает о прошлом — он поднимает состояние
задачи с диска. Если бы «текущий шаг» и «ожидание» жили в оперативной памяти
исполнителя, продолжить было бы нечем, и это сразу бы вылезло.

Экономия считается в токенах: сколько стоило бы начать сценарий заново против
того, во что обошлось продолжение.

Запуск:
    python check_pause.py                     # все проверки, модель по умолчанию
    python check_pause.py --модель ds-flash   # на своей модели
    python check_pause.py --в RESULTS.md      # записать отчёт
"""

from __future__ import annotations

import argparse
import functools
import json
import os
import shutil
import subprocess
import sys
import tempfile
from typing import Any

print = functools.partial(print, flush=True)

LINE = "-" * 78

# Каталог проекта: подпроцессу нужен именно он, чтобы найти пакет agent. Каталог
# с памятью прогона передаётся отдельно и живёт во временной папке.
КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))

# Сценарий проверки нарочно короткий: доказывается механика паузы, а не качество
# ответов, и пять шагов «напиши фичу» тут только сожгли бы лимиты.
СЦЕНАРИЙ = {
    "имя": "проверка паузы",
    "описание": "Три шага на трёх стадиях — чтобы останавливаться было где.",
    "триггеры": ["проверка паузы"],
    "шаги": [
        {"агент": "аналитик", "задача": "Назови в двух предложениях, что нужно "
                                        "выяснить для переноса справочника организаций.",
         "роль": "планирование", "стадия": "planning", "вход": ["запрос"],
         "может_спросить": True},
        {"агент": "исполнитель", "задача": "В двух предложениях скажи, что делать первым.",
         "роль": "исполнение", "стадия": "execution", "вход": ["аналитик"]},
        {"агент": "ревьюер", "задача": "В одном предложении скажи, что проверить.",
         "роль": "исполнение", "стадия": "validation", "вход": ["исполнитель"]},
    ],
}

ЗАПРОС = (
    "проверка паузы: перенести справочник организаций gissys.organization "
    "(поля id, name, inn, parent_id; наполняется из 1С) в модель Django"
)


def без_вопросов(сценарий: dict[str, Any]) -> dict[str, Any]:
    """Тот же сценарий, но шагам запрещено останавливаться за сведениями.

    Нужен для проверок, где остановку задаём мы сами. Первый прогон показал,
    почему: аналитик на любом запросе находил, о чём спросить, и вставал на
    первом же шаге — а тогда ни «пауза после второго шага», ни честная база для
    замера просто не наступают.
    """
    копия = json.loads(json.dumps(сценарий))
    for шаг in копия["шаги"]:
        шаг["может_спросить"] = False
    копия["имя"] = сценарий["имя"] + " без вопросов"
    копия["триггеры"] = [копия["имя"]]
    return копия


# --- работа в отдельном процессе ---------------------------------------------
# Каждый шаг проверки — свой процесс. Это и есть суть доказательства: продолжение
# не может опереться ни на что, кроме состояния на диске.

ПОДПРОГРАММА = r'''
import json, sys
sys.path.insert(0, %(корень)r)
from agent import MemoryAgent
from agent.scenarios import Scenario

команда = json.loads(sys.argv[1])
агент = MemoryAgent(base_dir=команда["память"], router_mode="выкл",
                    model_key=команда["модель"], temperature=0.0, max_tokens=400)
итог = {}
try:
    if команда["что"] == "запуск":
        агент.add_scenario(Scenario.from_dict(команда["сценарий"]))
        пауза_после = команда.get("пауза_после", 0)

        def после(результат, номер, всего):
            if пауза_после and номер == пауза_после:
                агент.pause_task()

        прогон = агент.run_scenario(команда["запрос"], name=команда["сценарий"]["имя"],
                                    on_result=после, по_шагам=команда.get("по_шагам", False))
    else:
        прогон = агент.resume_scenario(команда["задача"], ответ=команда.get("ответ", ""),
                                       по_шагам=команда.get("по_шагам", False))

    итог = {
        "задача": прогон.task_id,
        "шагов_в_прогоне": len(прогон.шаги),
        "токенов": прогон.токенов,
        "на_паузе": прогон.на_паузе,
        "причина": прогон.причина_паузы,
        "ожидание": прогон.ожидание,
        "ожидание_текст": прогон.ожидание_текст,
        "решение": (прогон.решение or {}).get("заголовок", ""),
    }
    состояние = агент.task_state()
    итог["состояние"] = состояние["словами"] if состояние["есть"] else "задача завершена"
except Exception as exc:
    итог = {"ошибка": f"{type(exc).__name__}: {exc}"}
finally:
    агент.close()
print("--ИТОГ--" + json.dumps(итог, ensure_ascii=False))
'''


def в_процессе(команда: dict[str, Any]) -> dict[str, Any]:
    """Выполняет команду в отдельном процессе и возвращает его итог.

    Отдельный процесс здесь не для скорости, а ради честности проверки: он не
    может опереться ни на что, кроме состояния задачи на диске.
    """
    готово = subprocess.run(
        [sys.executable, "-c", ПОДПРОГРАММА % {"корень": КОРЕНЬ},
         json.dumps(команда, ensure_ascii=False)],
        capture_output=True, text=True, cwd=КОРЕНЬ,
    )
    for строка in готово.stdout.splitlines():
        if строка.startswith("--ИТОГ--"):
            return json.loads(строка[len("--ИТОГ--"):])
    return {"ошибка": (готово.stderr or готово.stdout or "процесс ничего не вернул")[-300:]}


# --- проверки -----------------------------------------------------------------

def проверка_остановок(корень: str, модель: str) -> dict[str, Any]:
    """Пауза после каждого шага, продолжение из нового процесса."""
    print(f"\n{LINE}\n1. ПАУЗА НА КАЖДОМ ЭТАПЕ И ПРОДОЛЖЕНИЕ ИЗ НОВОГО ПРОЦЕССА\n{LINE}")
    итог: dict[str, Any] = {"название": "1. Пауза на каждом этапе", "остановки": []}

    сценарий = без_вопросов(СЦЕНАРИЙ)
    # После третьего шага останавливаться незачем: он последний, и пауза там
    # означает просто «сценарий кончился».
    for после_шага in (1, 2):
        память = os.path.join(корень, f"pause-{после_шага}")
        запуск = в_процессе({"что": "запуск", "память": память, "модель": модель,
                             "сценарий": сценарий, "запрос": ЗАПРОС,
                             "пауза_после": после_шага})
        if "ошибка" in запуск:
            print(f"  после шага {после_шага}: сбой — {запуск['ошибка'][:90]}")
            итог["остановки"].append({"после": после_шага, "ошибка": запуск["ошибка"]})
            continue

        print(f"  после шага {после_шага}: {запуск['состояние']}")
        # Процесс уже завершился. Продолжаем из нового — он читает только диск.
        продолжение = в_процессе({"что": "продолжение", "память": память,
                                  "модель": модель, "задача": запуск["задача"],
                                  "ответ": "SRID 3857, остальное как в gissys"})
        сделано = продолжение.get("шагов_в_прогоне", 0)
        print(f"      продолжение в новом процессе: шагов {сделано}, "
              f"{продолжение.get('токенов', 0)} токенов, "
              f"итог — {продолжение.get('решение') or продолжение.get('ошибка', '?')}")
        итог["остановки"].append({
            "после": после_шага,
            "состояние": запуск["состояние"],
            "на_паузе": запуск["на_паузе"],
            "причина": запуск["причина"],
            "шагов_до_паузы": запуск["шагов_в_прогоне"],
            "токенов_до_паузы": запуск["токенов"],
            "шагов_после": сделано,
            "токенов_после": продолжение.get("токенов", 0),
            "решение": продолжение.get("решение", ""),
            "ошибка": продолжение.get("ошибка", ""),
        })
    return итог


def проверка_перехода(корень: str, модель: str) -> dict[str, Any]:
    """Режим «по шагам»: остановка перед сменой стадии и подтверждение."""
    print(f"\n{LINE}\n2. ОСТАНОВКА НА ПЕРЕХОДЕ МЕЖДУ СТАДИЯМИ\n{LINE}")
    память = os.path.join(корень, "transition")
    сценарий = без_вопросов(СЦЕНАРИЙ)
    запуск = в_процессе({"что": "запуск", "память": память, "модель": модель,
                         "сценарий": сценарий, "запрос": ЗАПРОС, "по_шагам": True})
    print(f"  первый прогон: {запуск.get('состояние', запуск.get('ошибка'))}")
    на_переходе = запуск.get("причина") == "переход между стадиями"
    print(f"  встал на переходе: {'да' if на_переходе else 'нет'}")
    итог = {"название": "2. Остановка на переходе между стадиями",
            "встал": на_переходе, "запуск": запуск}
    if на_переходе:
        # Подтверждаем и идём дальше — снова до следующего перехода.
        дальше = в_процессе({"что": "продолжение", "память": память, "модель": модель,
                             "задача": запуск["задача"], "по_шагам": True})
        print(f"  после подтверждения: {дальше.get('состояние', дальше.get('ошибка'))}")
        итог["после_подтверждения"] = дальше
    return итог


def проверка_вопроса(корень: str, модель: str) -> dict[str, Any]:
    """Остановка, когда шагу не хватает сведений, и ответ человека."""
    print(f"\n{LINE}\n3. ОСТАНОВКА ЗА СВЕДЕНИЯМИ\n{LINE}")
    память = os.path.join(корень, "question")
    запуск = в_процессе({"что": "запуск", "память": память, "модель": модель,
                         "сценарий": СЦЕНАРИЙ,
                         "запрос": "проверка паузы: перенести НЕЧТО куда-то"})
    print(f"  первый прогон: {запуск.get('состояние', запуск.get('ошибка'))}")
    спросил = запуск.get("причина") == "не хватает сведений"
    print(f"  шаг спросил сам: {'да' if спросил else 'нет'}")
    итог = {"название": "3. Остановка за сведениями", "спросил": спросил,
            "вопрос": запуск.get("ожидание_текст", ""), "запуск": запуск}
    if спросил:
        продолжение = в_процессе({"что": "продолжение", "память": память,
                                  "модель": модель, "задача": запуск["задача"],
                                  "ответ": "Речь о справочнике организаций gissys.organization"})
        print(f"  после ответа: шагов {продолжение.get('шагов_в_прогоне', 0)}, "
              f"итог — {продолжение.get('решение') or продолжение.get('ошибка', '?')}")
        итог["продолжение"] = продолжение
    return итог


def проверка_экономии(корень: str, модель: str, остановки: list[dict]) -> dict[str, Any]:
    """Во что обошлось бы начать заново против продолжения с паузы."""
    print(f"\n{LINE}\n4. ЧТО ЭКОНОМИТ ПРОДОЛЖЕНИЕ\n{LINE}")
    память = os.path.join(корень, "full")
    целиком = в_процессе({"что": "запуск", "память": память, "модель": модель,
                          "сценарий": без_вопросов(СЦЕНАРИЙ), "запрос": ЗАПРОС})
    полный = целиком.get("токенов", 0)
    шагов = целиком.get("шагов_в_прогоне", 0)
    print(f"  сценарий целиком, без пауз: {полный} токенов, шагов {шагов}")
    if шагов < len(СЦЕНАРИЙ["шаги"]):
        # Если база сама не дошла до конца, сравнивать с ней нечего — первая
        # версия этой проверки на этом и обожглась, выдав «экономию −71%».
        print("  ВНИМАНИЕ: полный прогон не дошёл до конца, сравнение недостоверно")

    строки = []
    for о in остановки:
        если_заново = полный
        по_факту = о.get("токенов_после", 0)
        экономия = если_заново - по_факту
        доля = (экономия / если_заново * 100) if если_заново else 0
        print(f"  пауза после шага {о['после']}: продолжение стоило {по_факту} токенов "
              f"вместо {если_заново} — экономия {экономия} ({доля:.0f}%)")
        строки.append({"после": о["после"], "продолжение": по_факту,
                       "заново": если_заново, "экономия": экономия, "доля": round(доля)})
    return {"название": "4. Экономия продолжения", "целиком": полный,
            "шагов_в_базе": шагов, "строки": строки}


# --- отчёт --------------------------------------------------------------------

def отчёт(результаты: list[dict[str, Any]], путь: str, модель: str) -> None:
    части = [
        "# Результаты проверки состояния задачи",
        "",
        f"Живой прогон на модели `{модель}`. Между паузой и продолжением процесс",
        "завершается полностью: продолжение опирается только на состояние задачи,",
        "записанное на диск.",
        "",
    ]
    for итог in результаты:
        части.append(f"## {итог['название']}")
        части.append("")
        if "остановки" in итог:
            части.append("| пауза после шага | состояние на паузе | продолжение |")
            части.append("|---|---|---|")
            for о in итог["остановки"]:
                если = о.get("ошибка") or (
                    f"шагов {о.get('шагов_после', 0)}, "
                    f"{о.get('токенов_после', 0)} токенов, итог «{о.get('решение', '')}»")
                части.append(f"| {о['после']} | {о.get('состояние', '')} | {если} |")
            части.append("")
        if "встал" in итог:
            части.append(f"Сценарий встал на переходе между стадиями: "
                         f"**{'да' if итог['встал'] else 'нет'}**.")
            части.append("")
            части.append(f"Состояние на паузе: {итог['запуск'].get('состояние', '')}")
            if итог.get("после_подтверждения"):
                части.append("")
                части.append(f"После подтверждения: "
                             f"{итог['после_подтверждения'].get('состояние', '')}")
            части.append("")
        if "спросил" in итог:
            части.append(f"Шаг сам сообщил, что сведений не хватает: "
                         f"**{'да' if итог['спросил'] else 'нет'}**.")
            if итог.get("вопрос"):
                части.append("")
                части.append(f"> {итог['вопрос']}")
            if итог.get("продолжение"):
                п = итог["продолжение"]
                части.append("")
                части.append(f"После ответа человека сценарий доделал "
                             f"{п.get('шагов_в_прогоне', 0)} шаг(ов) и закончился "
                             f"решением «{п.get('решение', '')}».")
            части.append("")
        if "строки" in итог:
            части.append(f"Весь сценарий без пауз — {итог['целиком']} токенов.")
            части.append("")
            части.append("| пауза после шага | продолжение | начать заново | экономия |")
            части.append("|---|---|---|---|")
            for с in итог["строки"]:
                части.append(f"| {с['после']} | {с['продолжение']} | {с['заново']} "
                             f"| {с['экономия']} ({с['доля']}%) |")
            части.append("")

    with open(путь, "w", encoding="utf-8") as файл:
        файл.write("\n".join(части) + "\n")
    print(f"\nОтчёт записан: {путь}")


def main() -> int:
    разбор = argparse.ArgumentParser(
        description="Пауза на любом этапе и продолжение без повторных объяснений.",
        epilog=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    разбор.add_argument("--модель", dest="model", default="ds-flash", metavar="КЛЮЧ",
                        help="модель для всех шагов (по умолчанию ds-flash)")
    разбор.add_argument("--в", dest="out", default="", metavar="ПУТЬ",
                        help="записать отчёт, например RESULTS.md")
    аргументы = разбор.parse_args()

    рабочий = tempfile.mkdtemp(prefix="pause-")
    try:
        остановки = проверка_остановок(рабочий, аргументы.model)
        переход = проверка_перехода(рабочий, аргументы.model)
        вопрос = проверка_вопроса(рабочий, аргументы.model)
        экономия = проверка_экономии(рабочий, аргументы.model, остановки["остановки"])
        результаты = [остановки, переход, вопрос, экономия]
        if аргументы.out:
            отчёт(результаты, аргументы.out, аргументы.model)
    finally:
        shutil.rmtree(рабочий, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
