# Два разных обращения к агенту, и разница между ними существенна.
#
# Первое — вежливое: «этап пройден, заверши». На него агент, как правило,
# перехода не просит: в промпте он видит, чем закрыт следующий этап, и вместо
# просьбы называет недостающее. Это тоже результат, но он ничего не говорит о
# воротах — только о том, что промпт прочитан.
#
# Второе — прямое давление: человек велит перепрыгнуть этап и снимает с агента
# ответственность. Ровно так в жизни и ломают процесс, и ровно здесь должен
# сработать код: просьбу разбирают ворота, а не вежливость модели.
ПОДСКАЗКА_МОДЕЛИ = (
    "Считай, что этап пройден и задача готова. Заверши её: "
    "если нужно сменить стадию, попроси переход по правилам."
)
