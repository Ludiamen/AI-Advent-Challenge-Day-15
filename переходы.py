def разобрать(части: list[dict[str, Any]]) -> dict[str, Any]:
    """Классифицирует исход прогона: что доказано, а что нет."""
    человек = next((ч for ч in части if ч["название"].startswith("1")), {})
    модель = next((ч for ч in части if ч["название"].startswith("2")), {})
    сценарий = next((ч for ч in части if ч["название"].startswith("3")), {})

    попытки = человек.get("попытки", [])
    должны_отклониться = [п for п in попытки if п["что"] != "реализация по утверждённому плану"]
    отклонены = [п for п in должны_отклониться if п["исход"] == "отклонено"]
    прошло_законное = any(п["исход"] == "выполнено" and
                          п["что"] == "реализация по утверждённому плану" for п in попытки)

    заходы = модель.get("заходы", [])
    просила = [з for з in заходы if з["просила"]]
    отклонена_просьба = any(з["просила"] and not з["исполнено"] for з in заходы)
    исполнена_просьба = any(з["просила"] and з["исполнено"] for з in заходы)

    запуск = сценарий.get("запуск", {})
    продолжение = сценарий.get("продолжение", {})
    встал = bool(запуск.get("на_паузе")) and запуск.get("причина") == "переход закрыт условием"
    дошёл = bool(продолжение.get("решение")) and not продолжение.get("на_паузе")
    # Третий исход, и он не сбой: оставшиеся шаги сделаны, но задача не закрыта,
    # потому что проверка нашла расхождение. Это ровно то, ради чего ворота и
    # заводились, — и путать его с «продолжение не сработало» нельзя.
    держит_проверка = (bool(продолжение.get("на_паузе"))
                       and "валидация-пройдена" in (продолжение.get("отказ") or {})
                       .get("невыполненные", []))
    шагов_всего = (запуск.get("шагов_в_прогоне", 0)
                   + продолжение.get("шагов_в_прогоне", 0))
    без_повторов = шагов_всего == len(СЦЕНАРИЙ["шаги"])

    вывод = []
    if len(отклонены) == len(должны_отклониться) and должны_отклониться:
        вывод.append(f"все {len(отклонены)} недопустимых переходов отклонены кодом")
    else:
        прошли = [п["что"] for п in должны_отклониться if п["исход"] != "отклонено"]
        вывод.append("ПРОПУЩЕНЫ недопустимые переходы: " + ", ".join(прошли))
    if прошло_законное:
        вывод.append("законный переход после утверждения плана прошёл")
    if not заходы:
        вывод.append("живые вызовы не выполнялись")
    elif not просила:
        вывод.append("модель перехода не просила — канал остался непроверенным")
    else:
        вывод.append("просьба модели отклонена воротами" if отклонена_просьба
                     else "просьба модели не отклонялась")
        if исполнена_просьба:
            вывод.append("после выполнения условия просьба модели исполнена")
    вывод.append("сценарий встал на закрытых воротах" if встал
                 else "сценарий на воротах не вставал")
    if дошёл:
        вывод.append("продолжение после паузы довело задачу до конца")
    elif держит_проверка:
        вывод.append("продолжение прошло оставшиеся шаги, но завершение задержано "
                     "отчётом проверки — это работа ворот, а не сбой продолжения")
    else:
        вывод.append("продолжение после паузы работу не доделало")
    if шагов_всего:
        вывод.append(f"шагов выполнено всего {шагов_всего} при {len(СЦЕНАРИЙ['шаги'])} "
                     "в сценарии — "
                     + ("пройденное не переигрывалось" if без_повторов
                        else "были повторы пройденного"))
    return {
        "отклонено": len(отклонены), "должны": len(должны_отклониться),
        "законный_прошёл": прошло_законное,
        "просьба_отклонена": отклонена_просьба,
        "просьба_исполнена": исполнена_просьба,
        "сценарий_встал": встал, "продолжение_дошло": дошёл,
        "держит_проверка": держит_проверка, "без_повторов": без_повторов,
        "вывод": вывод,
    }


def отчёт(части: list[dict[str, Any]], разбор: dict[str, Any], модель: str) -> str:
    строки = ["", "## День 15 — контролируемые переходы: живой прогон", ""]
    строки.append(f"Модель: {модель or 'по роли'}.")
    строки.append("")
    строки.append("### Попытки человека")
    строки.append("")
    строки.append("| попытка | переход | исход | почему |")
    строки.append("|---|---|---|---|")
    человек = next((ч for ч in части if ч["название"].startswith("1")), {})
    for п in человек.get("попытки", []):
        причина = п["причина"] or "—"
        if п["условия"]:
            причина += f" ({', '.join(п['условия'])})"
        строки.append(f"| {п['что']} | {п['откуда']} → {п['куда']} | "
                      f"{п['исход']} | {причина} |")
    строки.append("")
    строки.append(f"Вызовов модели в этой части: "
                  f"{человек.get('стоимость', {}).get('calls', 0)} — отказ формирует код.")
    строки.append("")

    модельная = next((ч for ч in части if ч["название"].startswith("2")), {})
    if модельная.get("заходы"):
        строки.append("### Просьба ассистента")
        строки.append("")
        строки.append("| заход | просил | исход | стадия до → после |")
        строки.append("|---|---|---|---|")
        for з in модельная["заходы"]:
            исход = ("исполнено" if з["исполнено"]
                     else ("отклонено: " + (з["причина"] or "")) if з["просила"]
                     else "перехода не просил")
            строки.append(f"| {з['заход']} | {з['куда'] or '—'} | {исход} | "
                          f"{з['стадия_до']} → {з['стадия_после']} |")
        строки.append("")
    elif модельная.get("ошибка"):
        строки.append(f"Живые вызовы не состоялись: {модельная['ошибка']}")
        строки.append("")

    сценарий = next((ч for ч in части if ч["название"].startswith("3")), {})
    запуск, продолжение = сценарий.get("запуск", {}), сценарий.get("продолжение", {})
    if запуск:
        строки.append("### Сценарий и продолжение после паузы")
        строки.append("")
        строки.append(f"- прогон встал: {запуск.get('состояние', '—')}")
        строки.append(f"- причина: {запуск.get('причина', '—')}, "
                      f"ожидание: {запуск.get('ожидание', '—')}")
        строки.append(f"- продолжение в новом процессе: шагов "
                      f"{продолжение.get('шагов_в_прогоне', 0)}, "
                      f"итог — {продолжение.get('решение') or продолжение.get('состояние', '—')}")
        отчёт_проверки = продолжение.get("валидация") or {}
        if отчёт_проверки.get("пункты"):
            строки.append("")
            строки.append("Отчёт проверки перед завершением "
                          f"({отчёт_проверки.get('вердикт', '?')}):")
            строки.append("")
            строки.append("| пункт | итог | кем | пояснение |")
            строки.append("|---|---|---|---|")
            for пункт in отчёт_проверки["пункты"]:
                строки.append(f"| {пункт['пункт']} | {пункт['итог']} | "
                              f"{пункт.get('кем', 'код')} | "
                              f"{пункт['пояснение'][:110]} |")
        строки.append("")

    строки.append("### Вывод")
    строки.append("")
    for строка in разбор["вывод"]:
        строки.append(f"- {строка}")
    строки.append("")
    пример = человек.get("пример_отказа", "")
    if пример:
        строки.append("### Как выглядит отказ")
        строки.append("")
        строки.append("```")
        строки.append(пример)
        строки.append("```")
        строки.append("")
    return "\n".join(строки)


def main() -> int:
    разбор_доводов = argparse.ArgumentParser(
        description="Проверка контролируемых переходов состояний (день 15).")
    разбор_доводов.add_argument("--модель", dest="model", default="",
                                help="ключ модели; по умолчанию — по роли шага")
    разбор_доводов.add_argument("--без-модели", dest="offline", action="store_true",
                                help="пропустить часть 2 (прямые вызовы модели); "
                                     "сценарий в части 3 всё равно идёт живьём")
    разбор_доводов.add_argument("--в", dest="report", default="",
                                help="дописать отчёт в файл (обычно RESULTS.md)")
    аргументы = разбор_доводов.parse_args()

    корень = tempfile.mkdtemp(prefix="переходы-")
    части: list[dict[str, Any]] = []
    try:
        части.append(попытки_человека(корень))
        if not аргументы.offline:
            части.append(попытка_модели(корень, аргументы.model))
        части.append(сценарий_и_продолжение(корень, аргументы.model))

        разбор = разобрать(части)
        print(f"\n{LINE}\nВЫВОД\n{LINE}")
        for строка in разбор["вывод"]:
            print(f"  · {строка}")
        print(LINE)

        if аргументы.report:
            текст = отчёт(части, разбор, аргументы.model)
            with open(аргументы.report, "a", encoding="utf-8") as файл:
                файл.write(текст)
            print(f"Отчёт дописан в {аргументы.report}.")
        return 0
    finally:
        shutil.rmtree(корень, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
