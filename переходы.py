def попытки_человека(корень: str) -> dict[str, Any]:
    """Шесть попыток пройти мимо этапа. Модель не вызывается ни разу."""
    print(f"\n{LINE}\n1. ПОПЫТКИ ЧЕЛОВЕКА ПЕРЕЙТИ В НЕДОПУСТИМОЕ СОСТОЯНИЕ\n{LINE}")
    итог: dict[str, Any] = {"название": "1. Попытки человека", "попытки": []}
    а = агент(os.path.join(корень, "человек"))
    try:
        задача = а.start_task("цикл", "перенос справочника организаций")

        def попытка(что: str, куда: str) -> None:
            было = а.task.stage
            try:
                а.transition(куда)
            except ПереходОтклонён as отклонено:
                отказ = отклонено.отказ
                строка = {
                    "что": что, "откуда": было, "куда": куда, "исход": "отклонено",
                    "причина": отказ.причина,
                    "условия": [п.код for п in отказ.невыполненные],
                    "видно": [п.видно for п in отказ.невыполненные],
                    "текст": отказ.текст(),
                }
            else:
                строка = {"что": что, "откуда": было, "куда": куда,
                          "исход": "выполнено", "причина": "", "условия": [],
                          "видно": [], "текст": ""}
            итог["попытки"].append(строка)
            метка = "ОТКЛОНЕНО" if строка["исход"] == "отклонено" else "выполнено"
            подробность = строка["причина"]
            if строка["условия"]:
                подробность += f" ({', '.join(строка['условия'])})"
            print(f"  {метка:<10} {было:>10} → {куда:<11} {что}")
            if подробность.strip():
                print(f"             {подробность}")
            for видно in строка["видно"]:
                print(f"             сейчас: {видно}")

        попытка("прыжок через два этапа", "done")
        попытка("реализация без плана", "execution")

        задача.set_plan(["разобрать схему справочника",
                         "описать модель Django",
                         "перенести данные и проверить"])
        а.save_task()
        попытка("реализация по неутверждённому плану", "execution")

        а.approve_plan("Максим")
        попытка("реализация по утверждённому плану", "execution")

        попытка("проверка при незакрытых шагах", "validation")

        for _ in задача.шаги:
            задача.начать_шаг()
            задача.закончить_шаг("сделано вручную в проверке")
        а.save_task()
        а.transition("validation")
        а.remember_step("итог", "модель описана, данные перенесены")
        попытка("завершение без отчёта проверки", "done")

        # Отчёт с красным пунктом: проверка была, но не пройдена.
        задача.записать_валидацию({
            "вердикт": "не прошла", "красных": 1,
            "пункты": [{"пункт": "перенос данных сверен с 1С", "итог": "не прошло",
                        "пояснение": "сверка не проводилась", "кем": "код"}],
        })
        а.save_task()
        попытка("завершение с красным пунктом", "done")

        итог["стоимость"] = dict(а.client.spent)
        итог["отказов_в_журнале"] = len(задача.отказы)
        print(f"\n  Отказов записано в журнал задачи: {len(задача.отказы)}.")
        print(f"  Вызовов модели за всю часть: {а.client.spent['calls']} "
              f"(отказ формирует код, поэтому токены не тратятся).")
        итог["пример_отказа"] = next(
            (п["текст"] for п in итог["попытки"] if п["текст"]), "")
    finally:
        а.close()
    return итог


