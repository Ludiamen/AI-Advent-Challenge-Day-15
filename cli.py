def показать_переходы(agent: MemoryAgent) -> int:
    """Все стадии с пометкой «можно/нельзя и почему» — то же, что на странице."""
    если_нет = agent.task_state()
    if not если_нет["есть"]:
        print("Активной задачи нет: смотреть нечего. Взять: --задача ИД.")
        return 0
    print(LINE)
    print(f"ПЕРЕХОДЫ ЗАДАЧИ «{если_нет['task_id']}», сейчас {если_нет['этап']} "
          f"({если_нет['этап_словами']})")
    print(LINE)
    for строка in если_нет["переходы"]:
        if строка["текущая"]:
            print(f"  ● {строка['стадия']:<12} текущая стадия")
            continue
        метка = "→" if строка["можно"] else "🔒"
        print(f"  {метка} {строка['стадия']:<12} {строка['причина']}")
        for чего in строка.get("чего_не_хватает", []):
            print(f"       {чего['код']}: {чего['видно']}")
            if чего.get("вместо"):
                print(f"       чтобы открыть — {чего['вместо']}")
        if not строка["можно"] and len(строка.get("маршрут", [])) > 2:
            print(f"       законный маршрут: {' → '.join(строка['маршрут'])}")
    if если_нет.get("отказы"):
        print(LINE)
        print("Отклонённые попытки (последние):")
        for отказ in если_нет["отказы"][-5:]:
            print(f"  · {отказ.get('кто', '?'):<9} {отказ.get('откуда', '')} → "
                  f"{отказ.get('куда', '')}: {отказ.get('причина', '')}")
    print(LINE)
    return 0


