def диалог(agent: MemoryAgent, трейс: bool, сценарии: bool = True,
           по_шагам: bool = False) -> int:
    print(LINE)
    инфо = agent.info()
    print(f"Агент миграции ГИС. Пользователь «{инфо['user_id']}», сессия «{инфо['session']}».")
    print(f"Слои: {', '.join(инфо['layers']) or 'ни одного'}. "
          f"Маршрутизатор: {инфо['router_mode']}. Модель: {инфо['model_key']}.")
    print(f"Профиль: {инфо['profile']}."
          + (" Мастер настройки ещё не проходили — команда «настроить»."
             if инфо["needs_setup"] else ""))
    if инфо["scenarios"]:
        print(f"Сценариев: {len(инфо['scenarios'])} "
              f"({'запускаются по триггеру' if сценарии else 'автозапуск выключен'}).")
    if инфо["task"]:
        print(f"Задача «{инфо['task']['task_id']}», стадия {инфо['stage']} "
              f"(дальше можно: {', '.join(инфо['allowed']) or 'только завершить'}).")
    print("«помощь» — список команд, «выход» — закончить.")
    print(LINE)

    while True:
        try:
            строка = input("\nВы: ").strip()
        except (EOFError, KeyboardInterrupt):
            print("\nДо встречи.")
            return 0
        if not строка:
            continue
        нижний = строка.lower()

        if нижний in ("выход", "quit", "exit"):
            print("До встречи.")
            return 0
        if нижний in ("помощь", "?", "help"):
            print(ПОДСКАЗКА)
            continue
        if нижний == "память":
            показать_память(agent)
            continue
        if нижний == "журнал":
            показать_журнал(agent)
            continue
        if нижний == "профиль":
            показать_профиль(agent)
            continue
        if нижний == "знания":
            показать_знания(agent)
            continue
        if нижний == "решения":
            показать_решения(agent)
            continue
        if нижний == "задачи":
            показать_задачи(agent)
            continue
        if нижний == "состояние":
            показать_состояние(agent)
            continue
        if нижний == "инварианты":
            показать_инварианты(agent)
            continue
        if нижний == "переходы":
            показать_переходы(agent)
            continue
        if нижний == "условия":
            показать_условия(agent)
            continue
        if нижний in ("утвердить", "утвердить план"):
            try:
                подпись = agent.approve_plan()
            except AgentError as exc:
                print(f"Ошибка: {exc}")
                continue
            print(f"План утверждён: {подпись['кем']}, пунктов {подпись['пунктов']}. "
                  "Переход planning → execution открыт.")
            continue
        if нижний in ("проверить", "валидация"):
            try:
                отчёт = agent.validate_task()
            except AgentError as exc:
                print(f"Ошибка: {exc}")
                continue
            показать_отчёт(отчёт)
            continue
        if нижний == "пауза":
            try:
                задача = agent.pause_task()
            except AgentError as exc:
                print(f"Ошибка: {exc}")
                continue
            print(f"Остановлено. {задача.состояние_словами}")
            continue
        if нижний == "продолжить" or нижний.startswith("ответ "):
            ответ_человека = строка[6:].strip() if нижний.startswith("ответ ") else ""
            try:
                перед, после = наблюдатели(agent, трейс)
                итог = agent.resume_scenario(ответ=ответ_человека, on_step=перед,
                                             on_result=после, по_шагам=по_шагам)
            except AgentError as exc:
                print(f"Ошибка: {exc}")
                continue
            показать_прогон(итог, трейс)
            continue
        if нижний == "настроить":
            мастер_настройки(agent)
            continue
        if нижний == "заготовки":
            показать_заготовки()
            continue
        if нижний == "сценарии":
            показать_сценарии(agent)
            continue
        if нижний.startswith("заготовка "):
            try:
                профиль = agent.use_template(строка[10:].strip())
            except AgentError as exc:
                print(f"Ошибка: {exc}")
                continue
            print(f"Профиль: {preferences.summary(профиль)}")
            continue
        if нижний.startswith("настройка "):
            путь, _, значение = строка[10:].partition("=")
            раздел, _, ключ = путь.strip().partition("/")
            if not ключ or not значение.strip():
                print("Нужно «настройка раздел/ключ=значение».")
                continue
            try:
                agent.set_preference(раздел.strip(), ключ.strip(), значение.strip())
            except AgentError as exc:
                print(f"Ошибка: {exc}")
                continue
            print(f"Профиль: {preferences.summary(agent.profile())}")
            continue
        if нижний.startswith("сценарий "):
            имя, _, текст = строка[9:].partition(":")
            if not текст.strip():
                print("Нужно «сценарий ИМЯ: текст запроса».")
                continue
            try:
                перед, после = наблюдатели(agent, трейс)
                итог = agent.run_scenario(текст.strip(), name=имя.strip(),
                                          on_step=перед, on_result=после)
            except AgentError as exc:
                print(f"Ошибка: {exc}")
                continue
            показать_прогон(итог, трейс)
            continue
        if нижний == "трейс":
            трейс = not трейс
            print(f"Разбор промпта {'включён' if трейс else 'выключен'}.")
            continue
        if нижний.startswith("слои "):
            try:
                agent.set_layers(разобрать_слои(строка[5:]))
            except (SystemExit, AgentError) as exc:
                print(f"Ошибка: {exc}")
                continue
            print(f"Читаются слои: {', '.join(sorted(agent.layers)) or 'ни одного'}.")
            continue
        if нижний.startswith("стадия "):
            try:
                задача = agent.transition(строка[7:].strip())
            except ПереходОтклонён as отклонено:
                # Отказ печатается целиком: в нём и правило, и обоснование, и
                # то, что нужно сделать, чтобы переход открылся.
                print(отклонено.отказ.текст())
                continue
            except AgentError as exc:
                print(f"Отклонено: {exc}")
                continue
            print(f"Стадия: {задача.stage} ({задача.stage_label}). "
                  f"Дальше можно: {', '.join(задача.allowed()) or 'только завершить'}.")
            continue
        if нижний.startswith("шаг "):
            ключ, _, значение = строка[4:].partition("=")
            if not значение.strip():
                print("Нужно «шаг ключ=значение».")
                continue
            try:
                agent.remember_step(ключ.strip(), значение.strip())
            except AgentError as exc:
                print(f"Ошибка: {exc}")
                continue
            print(f"В рабочую память задачи: {ключ.strip()}.")
            continue
        if нижний == "план":
            try:
                ответ = agent.plan()
            except AgentError as exc:
                print(f"Ошибка: {exc}")
                continue
            print(f"\nАгент:\n{ответ.text}")
            if agent.task and agent.task.plan:
                print(f"\nВ рабочую память записано шагов: {len(agent.task.plan)}.")
            if трейс:
                показать_трейс(ответ)
            показать_расход(ответ)
            continue
        if нижний == "завершить":
            try:
                запись = agent.finish_task()
            except ПереходОтклонён as отклонено:
                print(отклонено.отказ.текст())
                continue
            except AgentError as exc:
                print(f"Ошибка: {exc}")
                continue
            print(f"Задача свёрнута в решение №{запись['id']}: {запись['заголовок']}")
            print(f"  {запись['решение'][:400]}")
            continue

        try:
            спросить(agent, строка, трейс, сценарии, по_шагам)
        except AgentError as exc:
            print(f"Ошибка: {exc}")
            continue


# --- точка входа --------------------------------------------------------------

def меняет_состояние(аргументы) -> bool:
    """Была ли команда действием, после которого диалог открывать не нужно.

    Без этого списка любая команда, которая что-то сделала и ничего не вернула
    явным `return`, проваливалась в диалоговый режим и молча ждала ввода: в
    терминале это выглядит как зависание, а в скрипте — как повисший процесс.
    Так случилось с ключами этого дня: `--утвердить-план` отрабатывал и вставал
    на приглашении «Вы:».
    """
    ключи = (
        "new_task", "stage", "step", "remember", "template", "preference",
        "add_invariant", "drop_invariant", "promote",
        # добавлено в Дне 15 — ворота перехода и условия
        "approve", "unapprove", "validate", "close_step",
        "add_condition", "drop_condition",
    )
    return any(getattr(аргументы, ключ, None) for ключ in ключи)


def main() -> int:
    аргументы = build_parser().parse_args()
    logging.basicConfig(
        level=logging.INFO if аргументы.логи else logging.WARNING,
        format="%(levelname)s %(name)s: %(message)s",
    )

    if аргументы.show_roles:
        return показать_роли()

    if аргументы.verify:
        return проверить_модели()

    слои = разобрать_слои(аргументы.layers)

    try:
        agent = MemoryAgent(
            model_key=аргументы.model,
            user_id=аргументы.user,
            session=аргументы.session,
            base_dir=аргументы.base_dir,
            layers=слои,
            router_mode=аргументы.router,
            threshold=аргументы.threshold,
            soft_check=аргументы.soft,
            follow_profile=not аргументы.loose,
            judge_semantic=not аргументы.no_judge,
            require_self_report=not аргументы.no_self_report,
        )
    except AgentError as exc:
        print(f"Ошибка: {exc}", file=sys.stderr)
        return 1

    try:
        return выполнить(agent, аргументы)
    except AgentError as exc:
        print(f"Ошибка: {exc}", file=sys.stderr)
        return 1
    finally:
        agent.close()


def выполнить(agent: MemoryAgent, аргументы) -> int:
    # Команда, которая что-то изменила и не задала вопроса, на этом и
    # заканчивается. Иначе «--стадия validation» молча открывал бы диалог, и
    # в скрипте это выглядит как зависший вызов.
    изменяющие = меняет_состояние(аргументы)

    if аргументы.forget:
        стёрто = agent.memory.short.clear(agent.session)
        print(f"Краткосрочная память сессии «{agent.session}» очищена: реплик стёрто {стёрто}.")
        print("Рабочая и долговременная память не тронуты — это разные слои.")
        return 0

    if аргументы.add_invariant:
        код, _, правило = аргументы.add_invariant.partition("=")
        if not правило.strip():
            print("Нужно «--инвариант код=правило».", file=sys.stderr)
            return 1
        слова = [с.strip() for с in аргументы.forbid.split(",") if с.strip()]
        инвариант = inv.Invariant(
            код=код.strip(), правило=правило.strip(), вид=аргументы.kind,
            тип=inv.ЗАПРЕТ_СЛОВ if слова else inv.СМЫСЛОВОЙ,
            значения=слова, почему=аргументы.why, вместо=аргументы.instead,
        )
        agent.add_invariant(инвариант, личный=аргументы.personal_invariant)
        уровень = "личный" if аргументы.personal_invariant else "проектный"
        print(f"Заведён {уровень} инвариант «{инвариант.код}» "
              f"({inv.ТИПЫ_СЛОВАМИ[инвариант.тип]}).")
        if not слова:
            print("Проверка смысловая: агент назовёт его в самоотчёте, а суждение "
                  "вынесет отдельная модель.")

    if аргументы.drop_invariant:
        снят = agent.remove_invariant(аргументы.drop_invariant)
        print(f"Инвариант «{аргументы.drop_invariant}» "
              + ("снят." if снят else "не найден."))

    if аргументы.promote:
        инвариант = agent.promote_decision(аргументы.promote)
        print(f"Решение №{аргументы.promote} возведено в инвариант «{инвариант.код}».")
        print(f"  {инвариант.правило}")
        if инвариант.почему:
            print(f"  Почему: {инвариант.почему}")

    if аргументы.show_invariants:
        return показать_инварианты(agent)

    if аргументы.show_templates:
        return показать_заготовки()

    if аргументы.setup:
        return мастер_настройки(agent)

    if аргументы.template:
        профиль = agent.use_template(аргументы.template)
        print(f"Профиль «{agent.user_id}» взят из заготовки «{аргументы.template}»: "
              f"{preferences.summary(профиль)}")

    if аргументы.preference:
        путь, _, значение = аргументы.preference.partition("=")
        раздел, _, ключ = путь.strip().partition("/")
        if not ключ or not значение.strip():
            print("Нужно «--настройка раздел/ключ=значение», например формат/длина=кратко.",
                  file=sys.stderr)
            return 1
        agent.set_preference(раздел.strip(), ключ.strip(), значение.strip())
        print(f"Предпочтение {раздел.strip()}/{ключ.strip()} = {значение.strip()}. "
              f"Профиль: {preferences.summary(agent.profile())}")

    if аргументы.new_task:
        задача = agent.start_task(аргументы.new_task, аргументы.title)
        print(f"Задача «{задача.task_id}» заведена, стадия {задача.stage}.")
    elif аргументы.task:
        задача = agent.use_task(аргументы.task)
        print(f"Задача «{задача.task_id}», стадия {задача.stage} ({задача.stage_label}).")

    if аргументы.drop_condition:
        if agent.remove_condition(аргументы.drop_condition):
            print(f"Условие «{аргументы.drop_condition}» снято.")
        else:
            print(f"Условия «{аргументы.drop_condition}» нет среди личных.",
                  file=sys.stderr)
            return 1

    if аргументы.add_condition:
        условие = tr.Условие(
            код=аргументы.add_condition,
            откуда=аргументы.from_stage, куда=аргументы.to_stage,
            что=аргументы.check, значение=аргументы.check_value,
            правило=аргументы.rule or f"условие «{аргументы.add_condition}»",
            почему=аргументы.why, вместо=аргументы.instead,
        )
        agent.add_condition(условие)
        print(f"Условие «{условие.код}» заведено: {условие.откуда} → {условие.куда}, "
              f"проверка «{условие.что}».")

    if аргументы.show_conditions:
        return показать_условия(agent)

    if аргументы.close_step:
        задача = agent.close_step()
        print(f"Шаг закрыт. {задача.состояние_словами}")

    if аргументы.approve:
        подпись = agent.approve_plan()
        print(f"План утверждён: {подпись['кем']}, пунктов {подпись['пунктов']}, "
              f"отпечаток {подпись['отпечаток']}.")
        print("Теперь открыт переход planning → execution.")

    if аргументы.unapprove:
        agent.unapprove_plan()
        print("Подпись с плана снята: переход к реализации снова закрыт.")

    if аргументы.validate:
        отчёт = agent.validate_task(ревизор=not аргументы.no_reviewer)
        показать_отчёт(отчёт)

    if аргументы.stage:
        задача = agent.transition(аргументы.stage)
        print(f"Стадия: {задача.stage}. Дальше можно: "
              f"{', '.join(задача.allowed()) or 'только завершить'}.")

    if аргументы.show_transitions:
        return показать_переходы(agent)

    if аргументы.step:
        ключ, _, значение = аргументы.step.partition("=")
        if not значение.strip():
            print("Нужно «--шаг ключ=значение».", file=sys.stderr)
            return 1
        agent.remember_step(ключ.strip(), значение.strip())
        print(f"В рабочую память задачи записано: {ключ.strip()}.")

    if аргументы.remember:
        слой, текст = аргументы.remember
        запись = agent.remember(слой, текст, key=аргументы.key, section=аргументы.section)
        print(f"Записано в {запись['слой']}"
              f"{'/' + запись['подслой'] if запись['подслой'] else ''} по правилу "
              f"«{запись['правило']}».")

    if аргументы.show_files:
        return показать_файлы(agent)
    if аргументы.show_memory:
        return показать_память(agent)
    if аргументы.show_profile:
        return показать_профиль(agent)
    if аргументы.show_knowledge:
        return показать_знания(agent)
    if аргументы.show_decisions:
        return показать_решения(agent)
    if аргументы.show_journal:
        return показать_журнал(agent)
    if аргументы.pause:
        задача = agent.pause_task()
        print(f"Задача «{задача.task_id}» остановлена. {задача.состояние_словами}")
        print("Текущий шаг доведён до конца — ответ модели, за который уже заплачено,")
        print("выбрасывать незачем. Продолжить: --продолжить.")
        return 0

    if аргументы.resume or аргументы.answer:
        if agent.task is None:
            print("Не указано, какую задачу продолжать: сначала --задача ИД.",
                  file=sys.stderr)
            return 1
        перед, после = наблюдатели(agent, аргументы.trace)
        итог = agent.resume_scenario(ответ=аргументы.answer, on_step=перед,
                                     on_result=после,
                                     по_шагам=аргументы.step_by_step)
        показать_прогон(итог, аргументы.trace)
        return 0

    if аргументы.show_state:
        return показать_состояние(agent)

    if аргументы.show_tasks:
        return показать_задачи(agent)
    if аргументы.show_scenarios:
        return показать_сценарии(agent)

    if аргументы.do_plan:
        ответ = agent.plan()
        print(f"\n{ответ.text}\n")
        if agent.task and agent.task.plan:
            print(f"В рабочую память записано шагов: {len(agent.task.plan)}.")
        if аргументы.trace:
            показать_трейс(ответ)
        показать_расход(ответ)
        return 0

    if аргументы.finish:
        запись = agent.finish_task()
        print(f"Задача свёрнута в решение №{запись['id']}: {запись['заголовок']}")
        print(запись["решение"])
        if запись.get("причина"):
            print(f"Почему: {запись['причина']}")
        print("Рабочая память задачи очищена — итог теперь живёт в журнале решений.")
        return 0

    вопрос = " ".join(аргументы.вопрос).strip()

    if аргументы.scenario:
        if not вопрос:
            print("Сценарию нужен запрос: python cli.py --сценарий «оцени задачу» \"текст\".",
                  file=sys.stderr)
            return 1

        перед, после = наблюдатели(agent, аргументы.trace)
        итог = agent.run_scenario(вопрос, name=аргументы.scenario,
                                  on_step=перед, on_result=после,
                                  по_шагам=аргументы.step_by_step)
        показать_прогон(итог, аргументы.trace)
        return 0

    if not вопрос:
        if изменяющие:
            return 0
        return диалог(agent, аргументы.trace, not аргументы.no_scenarios,
                      аргументы.step_by_step)

    спросить(agent, вопрос, аргументы.trace, not аргументы.no_scenarios,
             аргументы.step_by_step)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except ПереходОтклонён as отклонено:
        # Отказ в переходе — не сбой программы, а её работа. Поэтому наружу
        # выходит не стек, а тот же разбор, что видит человек на странице, и
        # ненулевой код возврата: скрипту важно знать, что переход не состоялся.
        print(отклонено.отказ.текст(), file=sys.stderr)
        sys.exit(1)
