"""Инварианты проекта: то, что агент не вправе нарушить ни при какой просьбе.

Инвариант — не пожелание и не настройка стиля. Это решение, уже принятое за
пределами разговора: выбранная архитектура, зафиксированный стек, бизнес-правило
заказчика. Пользователь может настаивать, приводить доводы и торопить — ответ не
изменится, потому что решает не модель, а код.

Почему инварианты живут отдельным модулем и отдельным файлом. В предыдущих днях
они лежали разделом профиля, и это был изъян: профиль принадлежит пользователю,
а инварианты — проекту. Переключил «--кто» — и получил другой набор запретов;
два пользователя одного проекта могли разойтись в том, что считать
недопустимым. Поэтому уровней теперь два:

  ПРОЕКТНЫЕ  память/инварианты.json — одни для всех, кто работает над проектом.
  ЛИЧНЫЕ     раздел профиля — могут только ДОБАВИТЬ запретов, но не снять
             проектные. Ослабить общее ограничение под себя нельзя: это ровно
             тот случай, ради которого инварианты и заводят.

Виды инвариантов взяты из задания дня и нужны не для красоты: по виду понятно,
откуда запрет и с кем спорить, если он мешает.

Типы проверок:

  запрет-слов       слова не должны встречаться ни в коде, ни в тексте (кроме
                    явного отказа от них: «Laravel здесь не подойдёт»);
  запрет-в-коде     слово можно упоминать, но нельзя писать на нём код;
  запрет-регулярок  выражение не должно встречаться нигде;
  смысловой         регуляркой не выражается — проверяется самоотчётом агента и
                    отдельным суждением дешёвой модели.

Тип «мягкий» из прежних дней упразднён. Он означал «в промпт просьбу положим, а
проверять не будем» — то есть инвариантом не был вовсе. Именно такими были
«1С — источник истины» и «совместимость по WMS/WFS», то есть как раз
бизнес-правило и архитектурное решение.

Публичное API:
  ВИДЫ, ТИПЫ, ЖЁСТКИЕ, СМЫСЛОВОЙ     — словарь предметной области
  Invariant                          — один инвариант
  InvariantStore(path)               — проектные инварианты в файле
  merge(проектные, личные)           — общий набор с пометкой уровня
  from_decision(запись)              — возвести решение из журнала в инвариант
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any

# --- виды: откуда взялся запрет ----------------------------------------------
СТЕК = "стек"
АРХИТЕКТУРА = "архитектура"
РЕШЕНИЕ = "решение"
БИЗНЕС_ПРАВИЛО = "бизнес-правило"
БЕЗОПАСНОСТЬ = "безопасность"
ВИДЫ = (СТЕК, АРХИТЕКТУРА, РЕШЕНИЕ, БИЗНЕС_ПРАВИЛО, БЕЗОПАСНОСТЬ)

ВИДЫ_СЛОВАМИ = {
    СТЕК: "ограничение по стеку",
    АРХИТЕКТУРА: "выбранная архитектура",
    РЕШЕНИЕ: "принятое техническое решение",
    БИЗНЕС_ПРАВИЛО: "бизнес-правило",
    БЕЗОПАСНОСТЬ: "требование безопасности",
}

# --- типы: чем проверяется ---------------------------------------------------
ЗАПРЕТ_СЛОВ = "запрет-слов"
ЗАПРЕТ_В_КОДЕ = "запрет-в-коде"
ЗАПРЕТ_РЕГУЛЯРОК = "запрет-регулярок"
СМЫСЛОВОЙ = "смысловой"
ЖЁСТКИЕ = (ЗАПРЕТ_СЛОВ, ЗАПРЕТ_В_КОДЕ, ЗАПРЕТ_РЕГУЛЯРОК)
ТИПЫ = ЖЁСТКИЕ + (СМЫСЛОВОЙ,)

ТИПЫ_СЛОВАМИ = {
    ЗАПРЕТ_СЛОВ: "поиск слов в ответе (код)",
    ЗАПРЕТ_В_КОДЕ: "поиск вызовов API в блоках кода (код)",
    ЗАПРЕТ_РЕГУЛЯРОК: "поиск по выражению (код)",
    СМЫСЛОВОЙ: "самоотчёт агента и суждение модели",
}

# --- уровни ------------------------------------------------------------------
ПРОЕКТНЫЙ = "проектный"
ЛИЧНЫЙ = "личный"
УРОВНИ = (ПРОЕКТНЫЙ, ЛИЧНЫЙ)

_КОД = re.compile(r"^[a-zA-Zа-яёА-ЯЁ0-9][a-zA-Zа-яёА-ЯЁ0-9_\-]{0,47}$")


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


class InvariantError(ValueError):
    """Негодное описание инварианта или попытка ослабить проектный."""


@dataclass
class Invariant:
    """Один инвариант: что запрещено, почему и что предложить вместо."""

    код: str
    правило: str
    вид: str = РЕШЕНИЕ
    тип: str = СМЫСЛОВОЙ
    значения: list[str] = field(default_factory=list)
    # Обоснование и альтернатива — не украшение. Именно они идут в отказ, и
    # именно поэтому отказ формирует код: текст не зависит от настроения модели
    # и одинаков при каждом конфликте.
    почему: str = ""
    вместо: str = ""
    источник: str = ""              # откуда взялся: решение №3, документ, устно
    уровень: str = ПРОЕКТНЫЙ
    создан: str = field(default_factory=_now)

    def validate(self) -> None:
        if not _КОД.match(self.код or ""):
            raise InvariantError(
                f"Негодный код инварианта «{self.код}»: нужны буквы, цифры, дефис "
                "и подчёркивание, до 48 символов."
            )
        if not (self.правило or "").strip():
            raise InvariantError(f"Инвариант «{self.код}» без формулировки правила.")
        if self.вид not in ВИДЫ:
            raise InvariantError(
                f"Инвариант «{self.код}»: неизвестный вид «{self.вид}». "
                f"Допустимы: {', '.join(ВИДЫ)}."
            )
        if self.тип not in ТИПЫ:
            raise InvariantError(
                f"Инвариант «{self.код}»: неизвестный тип «{self.тип}». "
                f"Допустимы: {', '.join(ТИПЫ)}."
            )
        if self.тип in ЖЁСТКИЕ and not self.значения:
            # Непроверяемый запрет хуже отсутствующего: он создаёт ложное
            # чувство защиты. Жёсткий инвариант обязан говорить, что искать.
            raise InvariantError(
                f"Жёсткий инвариант «{self.код}» без значений проверить нечем: "
                "нужен список слов или выражений."
            )
        if self.тип == ЗАПРЕТ_РЕГУЛЯРОК:
            for выражение in self.значения:
                try:
                    re.compile(выражение)
                except re.error as exc:
                    raise InvariantError(
                        f"Инвариант «{self.код}»: выражение «{выражение}» "
                        f"не компилируется: {exc}"
                    ) from exc
        if self.уровень not in УРОВНИ:
            raise InvariantError(
                f"Инвариант «{self.код}»: неизвестный уровень «{self.уровень}»."
            )

    @property
    def жёсткий(self) -> bool:
        return self.тип in ЖЁСТКИЕ

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Invariant":
        известные = {поле for поле in cls.__dataclass_fields__}
        return cls(**{к: з for к, з in data.items() if к in известные})

    def строкой(self) -> str:
        """Как инвариант выглядит в промпте и в отказе."""
        часть = f"[{self.код}] {self.правило}"
        if self.почему:
            часть += f" Почему так решено: {self.почему}"
        return часть

    def digest(self) -> str:
        проверка = "кодом" if self.жёсткий else "смыслом"
        return (f"{self.код:<24} {self.вид:<15} {self.тип:<17} {проверка:<8} "
                f"{self.уровень}")


class InvariantStore:
    """Проектные инварианты в отдельном файле — одни для всех пользователей."""

    def __init__(self, path: str) -> None:
        self.path = path

    def all(self) -> list[Invariant]:
        try:
            with open(self.path, encoding="utf-8") as файл:
                данные = json.load(файл)
        except FileNotFoundError:
            return []
        except (OSError, json.JSONDecodeError) as exc:
            raise InvariantError(f"Файл инвариантов «{self.path}» испорчен: {exc}") from exc
        if not isinstance(данные, list):
            return []
        return [Invariant.from_dict(и) for и in данные]

    def save_all(self, инварианты: list[Invariant]) -> None:
        временный = self.path + ".tmp"
        try:
            os.makedirs(os.path.dirname(os.path.abspath(self.path)), exist_ok=True)
            with open(временный, "w", encoding="utf-8") as файл:
                json.dump([и.to_dict() for и in инварианты], файл,
                          ensure_ascii=False, indent=2)
            os.replace(временный, self.path)
        except OSError as exc:
            raise InvariantError(f"Не удалось записать инварианты: {exc}") from exc

    def get(self, код: str) -> Invariant | None:
        код = (код or "").strip().lower()
        for инвариант in self.all():
            if инвариант.код.lower() == код:
                return инвариант
        return None

    def add(self, инвариант: Invariant) -> Invariant:
        инвариант.уровень = ПРОЕКТНЫЙ
        инвариант.validate()
        остальные = [и for и in self.all() if и.код.lower() != инвариант.код.lower()]
        остальные.append(инвариант)
        self.save_all(остальные)
        return инвариант

    def remove(self, код: str) -> bool:
        было = self.all()
        осталось = [и for и in было if и.код.lower() != (код or "").strip().lower()]
        if len(осталось) == len(было):
            return False
        self.save_all(осталось)
        return True

    def hard(self) -> list[Invariant]:
        return [и for и in self.all() if и.жёсткий]

    def semantic(self) -> list[Invariant]:
        return [и for и in self.all() if not и.жёсткий]


def merge(проектные: list[Invariant], личные: list[Invariant]) -> list[Invariant]:
    """Общий набор: проектные плюс личные, и личные не могут снять проектные.

    Совпадение кодов решается в пользу проектного инварианта. Это и есть
    единственное правило приоритета, которое здесь нужно: личный уровень
    существует, чтобы добавить себе запретов, а не чтобы отменить общие.
    """
    итог: list[Invariant] = []
    занятые: set[str] = set()
    for инвариант in проектные:
        инвариант.уровень = ПРОЕКТНЫЙ
        итог.append(инвариант)
        занятые.add(инвариант.код.lower())
    for инвариант in личные:
        if инвариант.код.lower() in занятые:
            continue
        инвариант.уровень = ЛИЧНЫЙ
        итог.append(инвариант)
    return итог


def from_decision(запись: dict[str, Any], код: str = "", вместо: str = "") -> Invariant:
    """Возводит запись журнала решений в инвариант.

    Замыкает то, ради чего журнал решений и ведётся: принятое решение перестаёт
    быть заметкой на память и становится ограничением, которое нельзя обойти.
    Обоснованием отказа служит та самая причина, по которой решение приняли, —
    поэтому объяснение получается содержательным, а не «так нельзя».
    """
    заголовок = (запись.get("заголовок") or "").strip()
    if not заголовок:
        raise InvariantError("У записи журнала нет заголовка — нечего возводить.")
    if not код:
        основа = re.sub(r"[^a-zA-Zа-яёА-ЯЁ0-9]+", "-", заголовок.lower()).strip("-")
        код = f"решение-{основа}"[:48].rstrip("-")
    альтернативы = запись.get("альтернативы") or []
    return Invariant(
        код=код,
        правило=(f"Решение принято и не пересматривается: {запись.get('решение', '')}"
                 .strip()),
        вид=РЕШЕНИЕ,
        тип=СМЫСЛОВОЙ,
        почему=(запись.get("причина") or "").strip(),
        вместо=вместо or ("; ".join(альтернативы) if альтернативы else ""),
        источник=f"журнал решений №{запись.get('id', '?')}",
    )
