_ПО_КЛЮЧУ = {(п.section, п.key): п for п in FIELDS}


def fields(section: str = "") -> list[Field]:
    return [п for п in FIELDS if not section or п.section == section]


def blank() -> dict[str, dict[str, Any]]:
    """Разделы предпочтений со значениями по умолчанию."""
    итог: dict[str, dict[str, Any]] = {раздел: {} for раздел in SECTIONS}
    for поле in FIELDS:
        итог[поле.section][поле.key] = поле.default
    return итог


def normalize(profile: dict[str, Any]) -> dict[str, Any]:
    """Дополняет профиль умолчаниями и приводит значения к допустимым.

    Профиль правят руками и присылают формы — значение может оказаться чем
    угодно. Приведение здесь, а не в десяти местах вызова: дальше по коду
    предпочтение всегда корректно.
    """
    профиль = dict(profile or {})
    умолчания = blank()
    for раздел, значения in умолчания.items():
        текущий = профиль.get(раздел)
        профиль[раздел] = dict(значения) | (текущий if isinstance(текущий, dict) else {})

    for поле in FIELDS:
        значение = профиль[поле.section].get(поле.key, поле.default)
        if поле.kind == "флаг":
            значение = _да_нет(значение)
        elif поле.kind == "выбор":
            значение = str(значение).strip().lower().replace(" ", "_")
            if значение not in поле.options:
                значение = поле.default
        else:
            значение = str(значение).strip()
        профиль[поле.section][поле.key] = значение
    return профиль


class PreferenceError(ValueError):
    """Недопустимое значение предпочтения."""


def set_value(profile: dict[str, Any], section: str, key: str, value: Any) -> dict[str, Any]:
    """Записывает одно предпочтение, отказываясь от значения вне списка.

    Отказ здесь важнее удобства: предпочтение «длина: очень кратко» выглядело бы
    сохранённым, в промпт не попало бы и проверку не прошло бы — и никто бы не
    понял почему.
    """
    поле = _ПО_КЛЮЧУ.get((section, key))
    if поле is None:
        допустимые = ", ".join(f"{п.section}/{п.key}" for п in FIELDS)
        raise PreferenceError(
            f"Неизвестное предпочтение «{section}/{key}». Допустимы: {допустимые}."
        )
    if поле.kind == "выбор":
        приведённое = str(value).strip().lower().replace(" ", "_")
        if приведённое not in поле.options:
            raise PreferenceError(
                f"Для «{поле.label}» допустимы: {', '.join(поле.options)}. Пришло: «{value}»."
            )
        value = приведённое
    elif поле.kind == "флаг":
        value = _да_нет(value)
    else:
        value = str(value).strip()

    профиль = dict(profile)
    профиль.setdefault(section, {})
    профиль[section] = dict(профиль[section]) | {key: value}
    return профиль


def word_limit(profile: dict[str, Any]) -> int:
    """Предел длины ответа в словах; 0 — без предела."""
    профиль = normalize(profile)
    return ПРЕДЕЛЫ_ДЛИНЫ.get(профиль[ФОРМАТ]["длина"], 0)


def describe(profile: dict[str, Any]) -> list[str]:
    """Строки предпочтений для системного промпта, в порядке разделов."""
    профиль = normalize(profile)
    строки = []
    for поле in FIELDS:
        # Единственная связка между полями: язык примеров бессмыслен, когда кода
        # не просили вовсе. Оставлять обе строки — значит отправить модели
        # противоречие и получить код вопреки профилю.
        if поле.key == "язык_кода" and профиль[ФОРМАТ]["код"] == "не_нужен":
            continue
        текст = поле.to_prompt(профиль[поле.section][поле.key])
        if текст:
            строки.append(текст)
    return строки


def summary(profile: dict[str, Any]) -> str:
    """Короткая сводка профиля одной строкой — для списков и заголовков."""
    п = normalize(profile)
    обращение = "на ты" if п[ОБРАЩЕНИЕ]["на_ты"] else "на вы"
    имя = п[ОБРАЩЕНИЕ]["имя"] or "без имени"
    return (f"{имя}, {обращение}, {п[ФОРМАТ]['длина']}, "
            f"код {п[ФОРМАТ]['код'].replace('_', ' ')}, {п[ФОРМАТ]['структура']}")


# --- проверка ответа ----------------------------------------------------------

@dataclass
class Deviation:
    """Одно расхождение ответа с профилем."""

    code: str
    label: str
    expected: str
    found: str
    hard: bool = True           # мягкое расхождение не вызывает переделку
    fix: str = ""               # что сказать модели на повторе

    def __str__(self) -> str:
        return f"{self.label}: ожидалось {self.expected}, в ответе {self.found}"

    def to_dict(self) -> dict[str, Any]:
        return {
            "код": self.code,
            "предпочтение": self.label,
            "ожидалось": self.expected,
            "в_ответе": self.found,
            "жёсткое": self.hard,
        }


REMINDER = """\
ВНИМАНИЕ. Предыдущий ответ разошёлся с профилем пользователя: {расхождения}
Профиль пользователь настроил сам. Перепиши ответ так, чтобы он ему отвечал.
Содержание сохрани, но требования профиля важнее полноты: лучше отдать главное
в заданном формате, чем всё — не в том."""


@dataclass
class PreferenceChecker:
    """Сверяет готовый ответ с тем, что пользователь просил.

    Проверяется не всё подряд, а только измеримое. «Тон инженерный» кодом не
    проверить — это остаётся просьбой в промпте. Зато длину, наличие кода, форму
    обращения и язык ответа проверить можно, и тогда персонализация перестаёт
    быть обещанием.
    """

    profile: dict[str, Any] = field(default_factory=blank)

    def check(self, answer: str) -> list[Deviation]:
        профиль = normalize(self.profile)
        текст = answer or ""
        проза = _БЛОК_КОДА.sub(" ", текст)
        расхождения: list[Deviation] = []

        for поле in FIELDS:
            if not поле.check:
                continue
            метод = getattr(self, f"_проверить_{поле.check}", None)
            if метод is None:
                continue
            расхождение = метод(профиль, поле, текст, проза)
            if расхождение is not None:
                расхождения.append(расхождение)
        return расхождения

    @staticmethod
    def _проверить_длина(профиль, поле, текст, проза) -> Deviation | None:
        предел = ПРЕДЕЛЫ_ДЛИНЫ.get(профиль[ФОРМАТ]["длина"], 0)
        if not предел:
            return None
        # Код в счёт длины не идёт: десять строк модели — это не «многословие»,
        # а ровно то, что просили показать.
        слов = len(_СЛОВО.findall(проза))
        if слов <= предел * ДОПУСК_ДЛИНЫ:
            return None
        return Deviation(
            code="длина", label=поле.label, expected=f"не больше {предел} слов",
            found=f"{слов} слов", hard=поле.hard,
            # Указание с числом работает заметно лучше расплывчатого «сократи»:
            # модель видит, сколько именно лишнего, и режет, а не переставляет
            # слова. На «сократи до 180 слов» ответ возвращался на 250 словах.
            fix=(f"в ответе {слов} слов вместо {предел} — убери не меньше "
                 f"{слов - предел} слов: выброси общие места и повторы целиком, "
                 f"а не сокращай каждую фразу"),
        )

    @staticmethod
    def _проверить_код(профиль, поле, текст, проза) -> Deviation | None:
        есть_код = bool(_БЛОК_КОДА.search(текст))
        режим = профиль[ФОРМАТ]["код"]
        if режим == "не_нужен" and есть_код:
            return Deviation(
                code="код", label=поле.label, expected="без кода",
                found="есть блок ```", hard=поле.hard,
                fix="убери блоки кода целиком и объясни то же самое словами",
            )
        if режим == "обязательно" and not есть_код:
            # Мягко: на вопрос «какие риски?» код не нужен, и требовать его —
            # значит гонять повторы на ровном месте.
            return Deviation(
                code="код", label=поле.label, expected="с кодом",
                found="кода нет", hard=False,
                fix="покажи код, если вопрос предполагает реализацию",
            )
        return None

    @staticmethod
    def _проверить_на_ты(профиль, поле, текст, проза) -> Deviation | None:
        на_ты = профиль[ОБРАЩЕНИЕ]["на_ты"]
        # Форма обращения ищется только в прозе: «you» в комментарии к коду
        # обращением к пользователю не является.
        if на_ты:
            найдено = _ВЫ.findall(проза)
            if найдено:
                return Deviation(
                    code="на_ты", label=поле.label, expected="на «ты»",
                    found=f"обращение на «вы» ({len(найдено)} раз)", hard=поле.hard,
                    fix="переведи все обращения к пользователю на «ты»",
                )
            return None
        найдено = _ТЫ.findall(проза)
        if найдено:
            return Deviation(
                code="на_ты", label=поле.label, expected="на «вы»",
                found=f"обращение на «ты» ({len(найдено)} раз)", hard=поле.hard,
                fix="переведи все обращения к пользователю на «вы»",
            )
        return None

    @staticmethod
    def _проверить_имя(профиль, поле, текст, проза) -> Deviation | None:
        имя = профиль[ОБРАЩЕНИЕ]["имя"]
        if not профиль[ОБРАЩЕНИЕ]["по_имени"] or not имя:
            return None
        if имя.lower() in проза.lower():
            return None
        return Deviation(
            code="имя", label=поле.label, expected=f"обращение по имени «{имя}»",
            found="имя не упомянуто", hard=поле.hard,
            fix=f"обратись к пользователю по имени: {имя}",
        )

    @staticmethod
    def _проверить_язык(профиль, поле, текст, проза) -> Deviation | None:
        кириллица = len(_КИРИЛЛИЦА.findall(проза))
        латиница = len(_ЛАТИНИЦА.findall(проза))
        всего = кириллица + латиница
        if всего < 40:
            # На короткой строке доля букв ничего не говорит: «OK» — это ещё не
            # переход на английский.
            return None
        доля_латиницы = латиница / всего
        язык = профиль[ФОРМАТ]["язык"]
        # Порог высокий намеренно: в русском инженерном тексте латиницы много —
        # имена классов, таблиц и библиотек.
        if язык == "русский" and доля_латиницы > 0.7:
            return Deviation(
                code="язык", label=поле.label, expected="русский",
                found=f"латиницы {доля_латиницы:.0%}", hard=поле.hard,
                fix="перепиши ответ по-русски, оставив латиницей только имена в коде",
            )
        if язык == "английский" and доля_латиницы < 0.3:
            return Deviation(
                code="язык", label=поле.label, expected="английский",
                found=f"латиницы {доля_латиницы:.0%}", hard=поле.hard,
                fix="rewrite the answer in English",
            )
        return None

    @staticmethod
    def _проверить_структура(профиль, поле, текст, проза) -> Deviation | None:
        форма = профиль[ФОРМАТ]["структура"]
        есть_список = bool(re.search(r"^\s*(?:\d+[.)]|[-*•])\s+", проза, re.MULTILINE))
        есть_таблица = "|" in проза and re.search(r"^\s*\|.*\|", проза, re.MULTILINE)
        if форма == "проза" and (есть_список or есть_таблица):
            найдено = "список" if есть_список else "таблица"
            return Deviation(code="структура", label=поле.label, expected="связный текст",
                             found=найдено, hard=False,
                             fix="изложи то же самое связным текстом")
        if форма == "списки" and not есть_список:
            return Deviation(code="структура", label=поле.label, expected="списки",
                             found="сплошной текст", hard=False,
                             fix="разложи ответ на пункты списка")
        if форма == "таблицы" and not есть_таблица:
            return Deviation(code="структура", label=поле.label, expected="таблицы",
                             found="таблицы нет", hard=False,
                             fix="подай сравнение таблицей")
        return None

    def reminder(self, deviations: list[Deviation]) -> str:
        перечень = "; ".join(
            f"{о.label} — {о.fix}" for о in deviations if о.hard and о.fix
        )
        return REMINDER.format(расхождения=перечень)


# --- мягкая проверка стиля ----------------------------------------------------
# Переехала сюда из agent/validator.py: тот занят инвариантами проекта, а это —
# про предпочтения пользователя. Разные вещи с разной силой: нарушение
# инварианта ответ блокирует, замечание по стилю — нет.

@dataclass
class SoftResult:
    """Вердикт мягкой проверки: замечания без права вето."""

    ok: bool = True
    notes: list[str] = field(default_factory=list)
    model_key: str = ""
    failed: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {"годится": self.ok, "замечания": self.notes,
                "модель": self.model_key, "сбой": self.failed}


class StyleJudge:
    """Проверяет стиль ответа дешёвой моделью. Замечания не блокируют."""

    def __init__(self, profile: Any, client: Any = None, model_key: str = "") -> None:
        self.profile = profile
        self.client = client
        self.model_key = model_key

    def check(self, answer: str) -> SoftResult:
        from agent import catalog, prompts
        from agent.llm import LLMError

        if self.client is None:
            return SoftResult(failed=True, notes=["модель для мягкой проверки не задана"])
        стиль = self.profile.load().get(ОБРАЩЕНИЕ) or {}
        требования = {к: з for к, з in стиль.items() if з not in ("", None, False)}
        формат = self.profile.load().get(ФОРМАТ) or {}
        требования.update({к: з for к, з in формат.items() if з not in ("", None, False)})
        if not требования:
            return SoftResult(notes=["требований к стилю в профиле нет"])

        ключ = self.model_key or catalog.for_role("мягкая-проверка")
        перечень = "\n".join(f"- {к}: {з}" for к, з in требования.items())
        сообщения = [
            {"role": "system", "content": prompts.SOFT_CHECK},
            {"role": "user",
             "content": f"Требования:\n{перечень}\n\nОтвет агента:\n{answer[:3000]}"},
        ]
        try:
            ответ = self.client.call(ключ, сообщения, max_tokens=300,
                                     temperature=0.0, low_effort=True)
        except LLMError as exc:
            return SoftResult(model_key=ключ, failed=True, notes=[str(exc)[:120]])

        import json as _json
        текст = ответ.text.strip()
        начало, конец = текст.find("{"), текст.rfind("}")
        if начало == -1 or конец <= начало:
            return SoftResult(model_key=ключ, failed=True,
                              notes=["проверяющая модель вернула неразбираемый ответ"])
        try:
            данные = _json.loads(текст[начало:конец + 1])
        except _json.JSONDecodeError:
            return SoftResult(model_key=ключ, failed=True,
                              notes=["проверяющая модель вернула неразбираемый ответ"])
        return SoftResult(ok=bool(данные.get("годится", True)),
                          notes=[str(з) for з in (данные.get("замечания") or [])],
                          model_key=ключ)
