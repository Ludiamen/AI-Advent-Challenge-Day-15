"""Предпочтения пользователя: одно описание полей на всё приложение.

В предыдущем дне профиль был свободным текстом «ключ — значение»: удобно
записывать, невозможно проверять. Фразу «отвечай кратко» код не умеет сверить с
ответом — он не знает, что «кратко» значит и в чём это измеряется. Поэтому здесь
предпочтения типизированы: у каждого поля есть раздел, набор допустимых
значений, умолчание, вопрос для мастера настройки, способ превратить значение в
строку системного промпта и — у измеримых — способ проверить ответ.

Всё это описано один раз, в FIELDS. Из одного описания собираются три вещи,
которые иначе разъезжались бы при первой же правке:

  * мастер настройки (agent/interview.py) — вопросы и допустимые ответы;
  * блок «профиль» в промпте (agent/builder.py) — текст предпочтений;
  * проверка ответа (PreferenceChecker) — сверка написанного с заявленным.

Про асимметрию проверок. Отсутствие кода в ответе проверяется однозначно:
блоков ``` нет — значит нет. А вот «код обязателен» строгой проверке не
поддаётся: на вопрос «какие тут риски?» код не нужен, и требовать его — значит
гонять повторы на ровном месте. Поэтому «не нужен» проверяется жёстко и вызывает
переделку, а «обязательно» остаётся замечанием. Так же и со структурой ответа.

Публичное API:
  FIELDS                      — все настраиваемые поля
  SECTIONS                    — разделы в порядке показа
  blank()                     — профиль с умолчаниями
  normalize(profile)          — дополнить профиль умолчаниями и привести типы
  set_value(profile, ...)     — записать одно поле с проверкой значения
  describe(profile)           — текст предпочтений для системного промпта
  summary(profile)            — короткая сводка для интерфейсов
  PreferenceChecker           — сверка ответа с профилем
  Deviation                   — одно расхождение
"""

from __future__ import annotations

