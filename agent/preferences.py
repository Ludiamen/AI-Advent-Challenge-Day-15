# Разделы профиля в порядке, в котором их показывают и спрашивают.
ОБРАЩЕНИЕ = "обращение"
ФОРМАТ = "формат"
SECTIONS = (ОБРАЩЕНИЕ, ФОРМАТ)

# Сколько слов помещается в каждую длину ответа. Значения не из головы: 180 слов
# — это примерно экран телефона, 450 — экран ноутбука. Ноль означает «без
# предела»: бывают вопросы, на которые короткий ответ был бы враньём.
ПРЕДЕЛЫ_ДЛИНЫ = {"кратко": 180, "средне": 450, "подробно": 0}

# Насколько можно превысить предел, прежде чем это считается расхождением.
# Без допуска агент переделывал бы ответ из-за одного лишнего слова.
ДОПУСК_ДЛИНЫ = 1.15

_БЛОК_КОДА = re.compile(r"```.*?```", re.DOTALL)
_СЛОВО = re.compile(r"[^\s]+")
_ВЫ = re.compile(r"(?<![\w])(вы|вам|вас|вами|ваш|ваша|ваше|ваши|вашего|вашей|"
                 r"ваших|вашим|вашими|вашем)(?![\w])", re.IGNORECASE)
_ТЫ = re.compile(r"(?<![\w])(ты|тебе|тебя|тобой|твой|твоя|твоё|твои|твоего|"
                 r"твоей|твоих|твоим|твоими|твоём)(?![\w])", re.IGNORECASE)
_КИРИЛЛИЦА = re.compile(r"[а-яёА-ЯЁ]")
_ЛАТИНИЦА = re.compile(r"[a-zA-Z]")


@dataclass(frozen=True)
class Field:
    """Одно настраиваемое предпочтение."""

    section: str
    key: str
    label: str                       # как называется в интерфейсах
    kind: str                        # выбор | текст | флаг
    default: Any
    question: str                    # вопрос мастера настройки
    hint: str = ""                   # пояснение под вопросом
    options: tuple[str, ...] = ()     # допустимые значения для kind="выбор"
    # Как значение превращается в строку системного промпта. Пустая строка
    # означает «это предпочтение в промпт не идёт» (например, предел слов идёт
    # вместе с длиной, а не отдельной строкой).
    to_prompt: Callable[[Any], str] = lambda значение: ""
    check: str = ""                  # код проверки в PreferenceChecker
    hard: bool = False               # расхождение вызывает переделку ответа


def _да_нет(значение: Any) -> bool:
    if isinstance(значение, bool):
        return значение
    return str(значение).strip().lower() in ("да", "true", "1", "ты", "на ты")


