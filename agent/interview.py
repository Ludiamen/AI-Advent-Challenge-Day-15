def from_template(name: str, profile: dict[str, Any] | None = None) -> dict[str, Any]:
    """Профиль по заготовке. Заготовка — это те же ответы мастера, но готовые."""
    заготовка = TEMPLATES.get(name)
    if заготовка is None:
        raise PreferenceError(
            f"Нет заготовки «{name}». Есть: {', '.join(TEMPLATES)}."
        )
    итог = apply(profile or {}, заготовка["ответы"], skip_empty=False)
    итог["контекст"] = заготовка["контекст"]
    return итог


def describe_templates() -> list[dict[str, str]]:
    return [
        {"имя": имя, "описание": з["описание"],
         "сводка": preferences.summary(preferences.normalize(apply({}, з["ответы"])))}
        for имя, з in TEMPLATES.items()
    ]
