"""Мастер настройки: короткое интервью, из которого получается профиль.

Это прямой сценарий из лекции: при первом обращении нового пользователя агент
задаёт несколько вопросов, складывает ответы в файл и дальше подмешивает их в
каждый запрос. Без этого «персонализация» сводится к тому, что профиль правит
разработчик в редакторе, а пользователь настроить агента под себя не может.

Вопросы не выдуманы здесь, а взяты из описания полей в agent/preferences.py:
добавили предпочтение — вопрос появился сам, и разъехаться им негде.

Мастер устроен так, чтобы его можно было пройти и в консоли, и формой в вебе, и
из теста. Поэтому он не читает ввод сам: он отдаёт список вопросов, принимает
словарь ответов и возвращает готовый профиль. Ввод — забота интерфейса.

Публичное API:
  questions()                    — вопросы мастера по порядку
  apply(profile, answers)        — применить ответы к профилю
  needs_setup(profile)           — профиль ещё не настраивали
  TEMPLATES                      — готовые профили-заготовки
  from_template(name)            — профиль по заготовке
"""

from __future__ import annotations

from typing import Any

from agent import preferences
from agent.preferences import Field, PreferenceError

# Признак того, что мастер проходили. Хранится в профиле, а не рядом: иначе
# «профиль настроен» и сам профиль разъедутся при копировании файла.
SETUP_FLAG = "настроен"


def questions() -> list[dict[str, Any]]:
    """Вопросы мастера: что спросить, как объяснить и что считать ответом."""
    итог = []
    for поле in preferences.FIELDS:
        итог.append(
            {
                "раздел": поле.section,
                "ключ": поле.key,
                "вопрос": поле.question,
                "пояснение": поле.hint,
                "тип": поле.kind,
                "варианты": list(поле.options) if поле.kind == "выбор"
                            else (["да", "нет"] if поле.kind == "флаг" else []),
                "умолчание": поле.default,
            }
        )
    return итог


def needs_setup(profile: dict[str, Any]) -> bool:
    """Профиль ещё не настраивали — стоит предложить мастер."""
    return not bool((profile or {}).get(SETUP_FLAG))


def apply(
    profile: dict[str, Any],
    answers: dict[str, Any],
    skip_empty: bool = True,
) -> dict[str, Any]:
    """Накладывает ответы мастера на профиль.

    Ключ ответа — «раздел/ключ» («формат/длина») или просто ключ, если он
    однозначен. Пустой ответ означает «оставить как есть»: пропустить вопрос —
    нормальное поведение, а не повод записать пустую строку.

    skip_empty=False нужен заготовкам: заготовка описывает профиль целиком, и
    пустое значение в ней означает именно пустое. Иначе выходит неожиданное:
    человек берёт заготовку «тимлид» с именем Максим, потом переключается на
    «инженер», у которой имени нет, — и остаётся Максимом, потому что пустое имя
    сочли пропущенным вопросом.
    """
    итог = dict(profile or {})
    for ключ, значение in (answers or {}).items():
        пусто = значение is None or (isinstance(значение, str) and not значение.strip())
        if пусто and skip_empty:
            continue
        if значение is None:
            значение = ""
        раздел, _, имя = str(ключ).partition("/")
        if not имя:
            имя, раздел = раздел, _раздел_поля(раздел)
        итог = preferences.set_value(итог, раздел, имя, значение)
    итог[SETUP_FLAG] = True
    return итог


def _раздел_поля(key: str) -> str:
    for поле in preferences.FIELDS:
        if поле.key == key:
            return поле.section
    raise PreferenceError(f"Неизвестное предпочтение «{key}».")


def field_by(section: str, key: str) -> Field | None:
    for поле in preferences.FIELDS:
        if поле.section == section and поле.key == key:
            return поле
    return None


