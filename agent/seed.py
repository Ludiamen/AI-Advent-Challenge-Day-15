def seed(memory: MemoryManager, force: bool = False) -> dict[str, int]:
    """Наполняет долговременную память проектными данными.

    По умолчанию работает только на пустой памяти: перезаписать профиль,
    который пользователь успел поправить под себя, — худшее, что может сделать
    инициализация. force=True наполняет поверх.
    """
    # Наполнение раздельное, и это не мелочь. Инварианты — проектные, они общие
    # и заводятся один раз. Профиль, знания, решения и сценарии принадлежат
    # пользователю, и второму пользователю их надо завести заново. Первая версия
    # смотрела на один общий признак «уже наполнено» — и новый пользователь
    # оставался без знаний и сценариев, потому что проектные инварианты уже
    # существовали.
    сводка = memory.long.stats()
    инварианты_есть = bool(memory.invariants.all())
    личное_есть = bool(сводка["решения"] or сводка["знания"])
    if инварианты_есть and личное_есть and not force:
        return {"профиль": 0, "инварианты": 0, "знания": 0, "решения": 0, "сценарии": 0}

    # Предпочтения — личное дело пользователя, и наполнять их за него нельзя:
    # тогда мастер настройки не сработает ни разу, а человек получит чужой
    # стиль ответов. Исключение одно: если пользователя зовут так же, как
    # заготовку («--кто тимлид»), он явно просит именно её.
    профиль = memory.long.profile.load()
    if memory.user_id in interview.TEMPLATES:
        профиль = interview.from_template(memory.user_id, профиль)
    профиль["user_id"] = memory.user_id
    # Ограничения и контекст описывают проект, а не человека, поэтому достаются
    # всем. Контекст заготовки, если он был, здесь и перекрывается: заготовка
    # описывает человека, а это — систему, которую переписывают.
    профиль["контекст"] = PROFILE["контекст"]
    профиль["ограничения"] = dict(PROFILE["ограничения"])
    memory.long.profile.save(профиль)

    # Инварианты кладутся в проектное хранилище, а не в профиль: они одни для
    # всех, кто работает над проектом, и заводятся один раз.
    добавлено_инвариантов = 0
    if not инварианты_есть or force:
        for инвариант in INVARIANTS:
            memory.invariants.add(inv.Invariant.from_dict(инвариант.to_dict()))
            добавлено_инвариантов += 1

    for факт in KNOWLEDGE:
        memory.long.knowledge.add(
            факт["id"], факт["текст"], topic=факт["тема"], tags=факт["теги"],
            source="документ с описанием legacy-системы",
        )

    существующие = {з["заголовок"] for з in memory.long.decisions.all()}
    добавлено = 0
    for решение in DECISIONS:
        if решение["title"] in существующие:
            continue
        memory.long.decisions.add(
            решение["title"], решение["decision"], решение["reason"],
            решение["alternatives"], source="зафиксировано на старте проекта",
        )
        добавлено += 1

    сценариев = 0
    существующие_сценарии = {с.имя.lower() for с in memory.long.scenarios.all()}
    for сценарий in SCENARIOS:
        if сценарий.имя.lower() in существующие_сценарии:
            continue
        memory.long.scenarios.add(сценарий)
        сценариев += 1

    return {
        "профиль": len(preferences.FIELDS) + len(PROFILE["ограничения"]) + 1,
        "инварианты": добавлено_инвариантов,
        "знания": len(KNOWLEDGE),
        "решения": добавлено,
        "сценарии": сценариев,
    }
