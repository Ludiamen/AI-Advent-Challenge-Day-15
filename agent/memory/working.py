"""Рабочая память: состояние текущей задачи.

Между «что мы только что сказали» и «что мы знаем про проект вообще» есть
третье — то, чем агент занят прямо сейчас: какая задача решается, на каком она
этапе, каков план и что уже собрано по ходу дела. Этот слой живёт от начала
задачи до её завершения: дольше отдельной реплики, но короче, чем знания о
проекте.

Устройство слоя — конечный автомат из четырёх стадий:

    planning -> execution -> validation -> done

Переходы разрешены не любые, и список разрешённых задан явно (TRANSITIONS).
Это единственный способ добавить детерминированности недетерминированной
модели: модель может сколько угодно «считать», что задача готова, но пока код
не увидел разрешённого перехода validation -> done, задача не завершена.

Одного списка стрелок, однако, мало. Стрелка planning -> execution есть всегда,
поэтому раньше переход проходил и при пустом плане: автомат проверял форму
маршрута, а не то, заслужен ли шаг. Условия перехода («план утверждён», «шаги
доведены», «проверка пройдена») живут отдельным модулем agent/transitions.py, а
рабочая память хранит следы, по которым их проверяют: подпись под планом, отчёт
валидации и журнал отклонённых попыток.

Одной стадии мало, чтобы вернуться к отложенной задаче. Стадия отвечает на
вопрос «на каком этапе работа», но не на два других, без которых продолжить
нельзя: на каком именно ШАГЕ мы стоим и ЧЕГО задача ждёт. Поэтому состояние
состоит из трёх частей:

    этап      stage      planning | execution | validation | done
    шаг       шаги[] + текущий_шаг — «архитектор, 2 из 5»
    ожидание  ОЖИДАНИЯ — продолжить | подтвердить-переход | ответ-пользователя |
              решение-человека | запустить | ничего

Пауза сделана флагом ПОВЕРХ стадии, а не пятой стадией автомата. Причина
простая: пауза возможна на любом этапе, и отдельная стадия paused потребовала
бы переходов из каждой стадии и обратно — граф удвоился бы, а базовые четыре
стадии перестали бы быть главными. Флаг же ортогонален: задача остаётся в
execution и при этом помечена остановленной, с записью, где именно она стоит и
чего ждёт.

Хранится состояние отдельным JSON-файлом на задачу, а не в базе диалога.
Причина прикладная: задачу надо уметь поднять через неделю после того, как
диалог, в котором она началась, был стёрт. Файл переживает и перезапуск, и
очистку истории, а прочитать его можно обычным cat.

Публичное API:
  STAGES, TRANSITIONS               — стадии и разрешённые переходы
  отпечаток(куски)                  — отпечаток плана и сделанной работы
  ОЖИДАНИЯ, ПРИЧИНЫ_ПАУЗЫ           — чего задача может ждать и почему стоит
  TaskStep                          — один шаг: имя, источник, стадия, состояние
  TaskState                         — состояние одной задачи
  .утвердить_план / .утверждение_актуально
  .записать_валидацию / .валидация_актуальна
  .записать_отказ / .записать_условия — следы попыток перехода
  WorkingMemory(directory)          — хранилище задач
  .create(task_id, title, ...)      — завести задачу
  .load(task_id) / .save(state)     — прочитать и записать
  .tasks()                          — список задач со сводкой
  .drop(task_id)                    — убрать задачу из рабочей памяти
"""

from __future__ import annotations

import hashlib
import json
import os
import re
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any

PLANNING = "planning"
EXECUTION = "execution"
VALIDATION = "validation"
DONE = "done"

# Базовые стадии лекции убирать нельзя — детализировать можно, но эти четыре
# остаются костяком.
STAGES = (PLANNING, EXECUTION, VALIDATION, DONE)

STAGE_LABELS = {
    PLANNING: "планирование",
    EXECUTION: "исполнение",
    VALIDATION: "проверка",
    DONE: "готово",
}

# Разрешённые переходы. Обратные стрелки не украшение: из исполнения можно
# вернуться в планирование (план оказался негодным), из проверки — в исполнение
# (нашли дефект). А вот перепрыгнуть из планирования сразу в готово нельзя.
TRANSITIONS: dict[str, tuple[str, ...]] = {
    PLANNING: (EXECUTION,),
    EXECUTION: (VALIDATION, PLANNING),
    VALIDATION: (EXECUTION, DONE),
    DONE: (),
}

# Одно правило на все имена, из которых получаются пути внутри каталога памяти:
# идентификатор задачи здесь и имя пользователя в long.py. Правило запрещающее,
# а не очищающее: «..» или «/» в имени — это не опечатка, которую надо молча
# исправить, а попытка выйти за пределы каталога памяти.
# --- ожидаемое действие -------------------------------------------------------
# Третья часть состояния, после этапа и шага. Отвечает на вопрос «что должно
# случиться, чтобы задача сдвинулась». Без неё человек, вернувшийся к задаче
# через день, видит «execution, шаг 3 из 5» и всё равно не знает, ждут от него
# чего-то или можно просто продолжать.
ЗАПУСТИТЬ = "запустить"                    # задача заведена, работа не начата
ПРОДОЛЖИТЬ = "продолжить"                  # можно идти дальше, никто ничего не ждёт
ПОДТВЕРДИТЬ = "подтвердить-переход"        # ждём согласия на смену стадии
ОТВЕТ = "ответ-пользователя"               # агенту не хватает сведений
РЕШЕНИЕ = "решение-человека"               # ответ не уложился в инварианты
НИЧЕГО = "ничего"                          # задача завершена
ОЖИДАНИЯ = (ЗАПУСТИТЬ, ПРОДОЛЖИТЬ, ПОДТВЕРДИТЬ, ОТВЕТ, РЕШЕНИЕ, НИЧЕГО)

ОЖИДАНИЯ_СЛОВАМИ = {
    ЗАПУСТИТЬ: "работа ещё не начиналась",
    ПРОДОЛЖИТЬ: "можно продолжать",
    ПОДТВЕРДИТЬ: "нужно подтвердить переход на следующую стадию",
    ОТВЕТ: "агенту не хватает сведений — нужен ваш ответ",
    РЕШЕНИЕ: "ответ не уложился в ограничения проекта — нужно ваше решение",
    НИЧЕГО: "задача завершена",
}

# Почему задача стоит. Причина хранится отдельно от ожидания: ожидание говорит,
# что сделать, причина — из-за чего остановились.
ПО_КОМАНДЕ = "по команде"
НА_ПЕРЕХОДЕ = "переход между стадиями"
НЕТ_СВЕДЕНИЙ = "не хватает сведений"
НАРУШЕН_ИНВАРИАНТ = "нарушен инвариант"
# Пятая причина появилась вместе с условиями перехода: сценарий дошёл до шага,
# который требует другой стадии, а ворота на эту стадию закрыты. Это не сбой и
# не нарушение — это ровно то, ради чего условия и заведены, поэтому у причины
# своё имя и свой текст, а не «ошибка исполнения».
ЗАКРЫТ_ПЕРЕХОД = "переход закрыт условием"
ПРИЧИНЫ_ПАУЗЫ = (ПО_КОМАНДЕ, НА_ПЕРЕХОДЕ, НЕТ_СВЕДЕНИЙ, НАРУШЕН_ИНВАРИАНТ,
                 ЗАКРЫТ_ПЕРЕХОД)

# Откуда взялся шаг. Задача по сценарию берёт шаги оттуда, заведённая руками —
# из плана, составленного на стадии планирования.
ИЗ_СЦЕНАРИЯ = "сценарий"
ИЗ_ПЛАНА = "план"

# Состояние отдельного шага.
ЖДЁТ = "ждёт"
ИДЁТ = "идёт"
ГОТОВ = "готов"
СОСТОЯНИЯ_ШАГА = (ЖДЁТ, ИДЁТ, ГОТОВ)

# Сколько знаков результата шага хранится в самом шаге. Полный текст лежит в
# собранных данных задачи; здесь — столько, чтобы в списке шагов было видно,
# чем шаг кончился.
ВЫЖИМКА_ШАГА = 400

# Сколько отклонённых попыток перехода хранится в состоянии задачи. Журнал
# нужен для разбора полётов, а не для вечности: последние два десятка отвечают
# на вопрос «куда рвались и почему не пустили», а файл задачи остаётся таким,
# чтобы его можно было прочитать глазами.
ОТКАЗОВ_В_ПАМЯТИ = 20


def отпечаток(куски: list[str]) -> str:
    """Короткий отпечаток набора строк.

    Им ловится правка задним числом: план, подписанный человеком, и план,
    переписанный после подписи, дают разные отпечатки — и утверждение
    перестаёт действовать само, без чьего-либо решения.
    """
    основа = "\n".join((к or "").strip() for к in куски)
    return hashlib.sha1(основа.encode("utf-8")).hexdigest()[:12]

SAFE_NAME = re.compile(r"^[a-zA-Zа-яёА-ЯЁ0-9][a-zA-Zа-яёА-ЯЁ0-9_\-]{0,63}$")
_ID = SAFE_NAME


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


class WorkingMemoryError(RuntimeError):
    """Ошибка работы с рабочей памятью."""


class TransitionError(WorkingMemoryError):
    """Запрошен переход, которого нет в списке разрешённых."""


@dataclass
class TaskStep:
    """Один шаг задачи: кто его делает, на какой стадии и чем он кончился."""

    номер: int
    имя: str
    источник: str = ИЗ_ПЛАНА          # сценарий или план
    стадия: str = EXECUTION
    состояние: str = ЖДЁТ
    выжимка: str = ""                 # чем кончился; полный текст — в collected
    может_спросить: bool = False      # шагу разрешено остановиться за сведениями

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "TaskStep":
        известные = {поле for поле in cls.__dataclass_fields__}
        return cls(**{к: з for к, з in data.items() if к in известные})


@dataclass
class TaskState:
    """Состояние одной задачи: этап, шаг, ожидание, данные и история переходов."""

    task_id: str
    title: str = ""
    stage: str = PLANNING
    plan: list[str] = field(default_factory=list)
    # --- шаг: вторая часть состояния -----------------------------------------
    шаги: list[TaskStep] = field(default_factory=list)
    # Номер шага, на котором стоим: 1..len(шаги). Ноль означает «шагов ещё нет
    # или работа не начиналась». Хранится именно номер, а не ссылка на объект:
    # состояние уезжает в JSON и поднимается из него через неделю.
    текущий_шаг: int = 0
    сценарий: str = ""                # имя сценария, если шаги пришли оттуда
    # Исходный запрос человека. Нужен, чтобы продолжить задачу в другом
    # процессе: шаги собирают свой вход из него и из результатов предыдущих
    # шагов, а держать его в оперативной памяти исполнителя — значит потерять
    # при первом же выходе.
    запрос: str = ""
    # --- ожидание и пауза: третья часть --------------------------------------
    ожидание: str = ЗАПУСТИТЬ
    ожидание_текст: str = ""          # пояснение словами: чего именно ждём
    пауза: bool = False
    причина_паузы: str = ""
    # Ответы человека на остановках «не хватает сведений». Хранятся отдельно от
    # собранных данных: это не результат работы агента, а то, что он спросил.
    ответы: list[dict[str, str]] = field(default_factory=list)
    # --- ворота перехода: чем заслужен следующий этап ------------------------
    # Подпись человека под планом. Хранится не флагом, а записью: кто, когда и
    # под каким именно планом подписался. Отпечаток нужен, чтобы правка плана
    # после утверждения не проезжала молча: она снимает утверждение сама, без
    # чьего-либо решения. Сами условия перехода живут в agent/transitions.py —
    # рабочая память хранит только следы, по которым их проверяют.
    план_утверждён: dict[str, Any] = field(default_factory=dict)
    # Отчёт проверки: чек-лист кодом плюс, если он был, вердикт модели-ревизора.
    отчёт_валидации: dict[str, Any] = field(default_factory=dict)
    # Журнал отклонённых попыток перехода: кто, куда рвался и почему не пустили.
    # Состоявшиеся переходы лежат отдельно, в transitions: удача и отказ — разные
    # события, и смешивать их в одном списке значит потерять и то и другое.
    отказы: list[dict[str, Any]] = field(default_factory=list)
    # Промежуточные результаты: то, что выяснили по ходу задачи. Ключ —
    # о чём речь, значение — сам результат. Живёт ровно столько, сколько задача.
    collected: dict[str, str] = field(default_factory=dict)
    # Журнал переходов: кто, когда и почему сменил стадию. Нужен на разборе
    # полётов — по нему видно, сколько раз задача возвращалась на доработку.
    transitions: list[dict[str, str]] = field(default_factory=list)
    created_at: str = field(default_factory=_now)
    updated_at: str = field(default_factory=_now)

    @property
    def stage_label(self) -> str:
        return STAGE_LABELS.get(self.stage, self.stage)

    @property
    def finished(self) -> bool:
        return self.stage == DONE

    def allowed(self) -> tuple[str, ...]:
        """Куда из текущей стадии можно перейти."""
        return TRANSITIONS.get(self.stage, ())

    def can_go(self, stage: str) -> bool:
        return stage in self.allowed()

    def transition(self, stage: str, note: str = "") -> None:
        """Переводит задачу на новую стадию; запрещённый переход — ошибка.

        Именно здесь недетерминированность модели упирается в код: текст ответа
        может сколько угодно утверждать, что «всё готово», — стадию меняет
        только явный разрешённый переход.
        """
        if stage not in STAGES:
            raise TransitionError(
                f"Неизвестная стадия «{stage}». Допустимы: {', '.join(STAGES)}."
            )
        if not self.can_go(stage):
            разрешено = ", ".join(self.allowed()) or "никуда: задача завершена"
            raise TransitionError(
                f"Переход {self.stage} -> {stage} не разрешён. "
                f"Из стадии «{self.stage}» можно: {разрешено}."
            )
        self.transitions.append(
            {"from": self.stage, "to": stage, "note": note, "at": _now()}
        )
        self.stage = stage
        # Сменили этап — прежнее ожидание больше не действует. Оставить его
        # значило бы показывать «подтвердите переход» уже после перехода.
        self.ждать(НИЧЕГО if stage == DONE else ПРОДОЛЖИТЬ)
        self.updated_at = _now()

    # --- ворота: следы, по которым проверяют условия перехода ----------------

    @property
    def отпечаток_плана(self) -> str:
        return отпечаток(self.plan)

    @property
    def отпечаток_работы(self) -> str:
        """Отпечаток сделанного: состояния шагов и ключи собранных данных.

        По нему видно, менялась ли работа после проверки. Без этого отчёт
        валидации становится вечной индульгенцией: прошёл один раз — и дальше
        хоть переписывай всё заново.
        """
        return отпечаток(
            [f"{ш.номер}:{ш.состояние}:{ш.имя}" for ш in self.шаги]
            + sorted(self.collected)
        )

    def утвердить_план(self, кем: str = "человек", пояснение: str = "") -> dict[str, Any]:
        """Подписывает план. Без плана подписывать нечего — это ошибка."""
        if not self.plan:
            raise WorkingMemoryError(
                "Утверждать нечего: плана нет. Сначала составьте план."
            )
        self.план_утверждён = {
            "кем": (кем or "человек").strip(),
            "когда": _now(),
            "отпечаток": self.отпечаток_плана,
            "пунктов": len(self.plan),
            "пояснение": (пояснение or "").strip(),
        }
        self.updated_at = _now()
        return dict(self.план_утверждён)

    def снять_утверждение(self, почему: str = "") -> None:
        """Снимает подпись с плана — например, когда план решили переделать."""
        self.план_утверждён = {}
        self.updated_at = _now()

    @property
    def утверждение_актуально(self) -> bool:
        """Подписан ли ТОТ САМЫЙ план, который лежит в задаче сейчас."""
        подпись = self.план_утверждён
        return bool(подпись) and подпись.get("отпечаток") == self.отпечаток_плана

    def записать_валидацию(self, отчёт: dict[str, Any]) -> dict[str, Any]:
        """Кладёт отчёт проверки в состояние задачи, отмечая, к чему он относится."""
        запись = dict(отчёт or {})
        запись.setdefault("когда", _now())
        запись["отпечаток"] = self.отпечаток_работы
        self.отчёт_валидации = запись
        self.updated_at = _now()
        return запись

    @property
    def валидация_актуальна(self) -> bool:
        отчёт = self.отчёт_валидации
        return bool(отчёт) and отчёт.get("отпечаток") == self.отпечаток_работы

    def записать_отказ(self, отказ: dict[str, Any]) -> None:
        """Запоминает отклонённую попытку перехода.

        Именно эта запись и превращает «ассистент не может перепрыгнуть этап» из
        обещания в проверяемый факт: попытка, её источник и причина отказа
        остаются в файле задачи и переживают перезапуск.
        """
        self.отказы.append(dict(отказ or {}))
        if len(self.отказы) > ОТКАЗОВ_В_ПАМЯТИ:
            self.отказы = self.отказы[-ОТКАЗОВ_В_ПАМЯТИ:]
        self.updated_at = _now()

    def записать_условия(self, куда: str, проверки: list[dict[str, Any]],
                         кто: str = "") -> None:
        """Дописывает к состоявшемуся переходу то, чем он был заслужен."""
        if not self.transitions:
            return
        последний = self.transitions[-1]
        if последний.get("to") != куда:
            return
        последний["кто"] = кто
        последний["условия"] = [
            {"код": п.get("код", ""), "видно": п.get("видно", "")} for п in проверки
        ]
        self.updated_at = _now()

    # --- шаг: где мы стоим ---------------------------------------------------

    @property
    def шагов(self) -> int:
        return len(self.шаги)

    @property
    def шаг(self) -> TaskStep | None:
        """Текущий шаг или None, если шагов нет и работа не начата."""
        if 1 <= self.текущий_шаг <= len(self.шаги):
            return self.шаги[self.текущий_шаг - 1]
        return None

    @property
    def шаг_словами(self) -> str:
        шаг = self.шаг
        if шаг is None:
            return "шагов нет" if not self.шаги else "все шаги пройдены"
        return f"{шаг.имя} ({self.текущий_шаг} из {len(self.шаги)}, {шаг.источник})"

    def set_steps(self, шаги: list[TaskStep], сценарий: str = "") -> None:
        """Задаёт список шагов задачи и ставит указатель на первый."""
        self.шаги = list(шаги)
        self.сценарий = сценарий
        self.текущий_шаг = 1 if шаги else 0
        for номер, шаг in enumerate(self.шаги, 1):
            шаг.номер = номер
        self.updated_at = _now()

    def начать_шаг(self) -> TaskStep | None:
        шаг = self.шаг
        if шаг is not None:
            шаг.состояние = ИДЁТ
            # Работа пошла — «ещё не начиналась» больше не про эту задачу.
            if self.ожидание == ЗАПУСТИТЬ:
                self.ждать(ПРОДОЛЖИТЬ)
            self.updated_at = _now()
        return шаг

    def закончить_шаг(self, результат: str = "") -> None:
        """Отмечает текущий шаг выполненным и переводит указатель на следующий.

        Указатель двигается здесь, а не в исполнителе сценария: именно эта
        запись, легшая на диск, и позволяет продолжить работу в другом процессе.
        """
        шаг = self.шаг
        if шаг is None:
            return
        шаг.состояние = ГОТОВ
        шаг.выжимка = (результат or "").strip()[:ВЫЖИМКА_ШАГА]
        if self.текущий_шаг <= len(self.шаги):
            self.текущий_шаг += 1
        self.updated_at = _now()

    @property
    def шаги_пройдены(self) -> bool:
        return bool(self.шаги) and self.текущий_шаг > len(self.шаги)

    # --- ожидание и пауза ----------------------------------------------------

    def ждать(self, что: str, пояснение: str = "") -> None:
        """Записывает, чего задача ждёт. Значение вне перечня — ошибка."""
        if что not in ОЖИДАНИЯ:
            raise WorkingMemoryError(
                f"Неизвестное ожидание «{что}». Допустимы: {', '.join(ОЖИДАНИЯ)}."
            )
        self.ожидание = что
        self.ожидание_текст = (пояснение or ОЖИДАНИЯ_СЛОВАМИ.get(что, "")).strip()
        self.updated_at = _now()

    def остановить(self, причина: str, ожидание: str = ПРОДОЛЖИТЬ,
                   пояснение: str = "") -> None:
        """Ставит задачу на паузу. Стадия при этом не меняется — пауза поверх неё."""
        if причина not in ПРИЧИНЫ_ПАУЗЫ:
            raise WorkingMemoryError(
                f"Неизвестная причина паузы «{причина}». "
                f"Допустимы: {', '.join(ПРИЧИНЫ_ПАУЗЫ)}."
            )
        self.пауза = True
        self.причина_паузы = причина
        self.ждать(ожидание, пояснение)

    def продолжить(self) -> None:
        """Снимает паузу. Ожидание возвращается к «можно продолжать»."""
        self.пауза = False
        self.причина_паузы = ""
        self.ждать(НИЧЕГО if self.finished else ПРОДОЛЖИТЬ)

    def ответить(self, текст: str) -> None:
        """Принимает ответ человека на остановку «не хватает сведений».

        Ответ ложится отдельным списком, а не в собранные данные: собранное —
        это то, что выяснил агент, а здесь то, что сказал человек. На разборе
        полётов разница важна.
        """
        текст = (текст or "").strip()
        if not текст:
            raise WorkingMemoryError("Пустой ответ не принимается.")
        шаг = self.шаг
        self.ответы.append({
            "шаг": шаг.имя if шаг else "",
            "стадия": self.stage,
            "вопрос": self.ожидание_текст,
            "ответ": текст,
            "когда": _now(),
        })
        self.продолжить()

    @property
    def состояние_словами(self) -> str:
        """Одна строка, по которой видно всё: этап, шаг и чего ждём."""
        куски = [f"этап {self.stage_label}"]
        if self.шаги:
            куски.append(f"шаг {self.шаг_словами}")
        куски.append("на паузе" if self.пауза else "идёт")
        куски.append(f"ждём: {self.ожидание_текст or ОЖИДАНИЯ_СЛОВАМИ.get(self.ожидание, '')}")
        return "; ".join(куски)

    def remember(self, key: str, value: str) -> None:
        """Кладёт промежуточный результат в собранные данные задачи."""
        key = (key or "").strip()
        if not key:
            raise WorkingMemoryError("У промежуточного результата должен быть ключ.")
        self.collected[key] = (value or "").strip()
        self.updated_at = _now()

    def __post_init__(self) -> None:
        # Пояснение ожидания заполняется само: поле по умолчанию пустое, и без
        # этого свежая задача показывает «ожидание: запустить — » с пустотой
        # после тире.
        if not self.ожидание_текст:
            self.ожидание_текст = ОЖИДАНИЯ_СЛОВАМИ.get(self.ожидание, "")

    def set_plan(self, steps: list[str]) -> None:
        """Записывает план и превращает его пункты в шаги задачи.

        Шаг — единое понятие: у задачи по сценарию шаги приходят оттуда, у
        заведённой руками — из плана. Тогда пауза и продолжение работают в обоих
        случаях одинаково, а не только для сценариев. Шаги сценария план не
        затирает: там свои исполнители, и подменять их пунктами плана нельзя.
        """
        # Утверждение плана здесь не снимается явно, и это сделано нарочно:
        # подпись хранит отпечаток того плана, под которым её поставили, и
        # новый план просто перестаёт ей соответствовать. Так в задаче остаётся
        # видно, что план когда-то утверждали и переписали после этого.
        self.plan = [ш.strip() for ш in steps if ш.strip()]
        if not self.сценарий:
            self.set_steps([
                TaskStep(номер=н, имя=пункт, источник=ИЗ_ПЛАНА, стадия=EXECUTION)
                for н, пункт in enumerate(self.plan, 1)
            ])
        self.updated_at = _now()

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "TaskState":
        известные = {поле for поле in cls.__dataclass_fields__}
        значения = {к: з for к, з in data.items() if к in известные}
        # Шаги в файле лежат словарями — поднимаем их обратно в объекты, иначе
        # продолжение задачи из другого процесса свалится на первом же обращении
        # к полю шага.
        значения["шаги"] = [
            ш if isinstance(ш, TaskStep) else TaskStep.from_dict(ш)
            for ш in значения.get("шаги", [])
        ]
        return cls(**значения)

    def digest(self) -> str:
        """Короткая сводка задачи одной строкой — для списков и логов."""
        часть = f"{self.task_id} [{self.stage_label}"
        if self.пауза:
            часть += ", на паузе"
        часть += f"] {self.title or '—'}"
        if self.шаги:
            часть += f"; шаг {self.текущий_шаг} из {len(self.шаги)}"
        часть += f"; собрано записей {len(self.collected)}"
        if self.plan:
            часть += "; план " + ("утверждён" if self.утверждение_актуально else "не утверждён")
        if self.отчёт_валидации:
            часть += "; проверка " + (self.отчёт_валидации.get("вердикт") or "?")
        return часть


class WorkingMemory:
    """Хранилище задач: по JSON-файлу на задачу в отдельном каталоге."""

    layer = "рабочая"

    def __init__(self, directory: str) -> None:
        self.directory = directory
        os.makedirs(directory, exist_ok=True)

    def _path(self, task_id: str) -> str:
        if not _ID.match(task_id or ""):
            raise WorkingMemoryError(
                f"Недопустимый идентификатор задачи «{task_id}»: нужны буквы, цифры, "
                "дефис и подчёркивание, до 64 символов."
            )
        return os.path.join(self.directory, f"{task_id}.json")

    def exists(self, task_id: str) -> bool:
        return os.path.exists(self._path(task_id))

    def create(
        self,
        task_id: str,
        title: str = "",
        plan: list[str] | None = None,
        overwrite: bool = False,
    ) -> TaskState:
        """Заводит новую задачу в стадии planning."""
        if self.exists(task_id) and not overwrite:
            raise WorkingMemoryError(
                f"Задача «{task_id}» уже есть в рабочей памяти. "
                "Возьмите её (--задача) или укажите другой идентификатор."
            )
        состояние = TaskState(task_id=task_id, title=title, plan=plan or [])
        self.save(состояние)
        return состояние

    def load(self, task_id: str) -> TaskState:
        """Поднимает состояние задачи с диска — в том числе спустя дни."""
        путь = self._path(task_id)
        try:
            with open(путь, encoding="utf-8") as файл:
                данные = json.load(файл)
        except FileNotFoundError:
            raise WorkingMemoryError(
                f"Задачи «{task_id}» нет в рабочей памяти. Список: --задачи."
            ) from None
        except (OSError, json.JSONDecodeError) as exc:
            raise WorkingMemoryError(f"Файл задачи «{task_id}» испорчен: {exc}") from exc
        return TaskState.from_dict(данные)

    def save(self, state: TaskState) -> None:
        """Записывает состояние задачи атомарно: сначала временный файл, потом замена."""
        state.updated_at = _now()
        путь = self._path(state.task_id)
        временный = путь + ".tmp"
        try:
            with open(временный, "w", encoding="utf-8") as файл:
                json.dump(state.to_dict(), файл, ensure_ascii=False, indent=2)
            os.replace(временный, путь)
        except OSError as exc:
            raise WorkingMemoryError(f"Не удалось сохранить задачу «{state.task_id}»: {exc}") from exc

    def tasks(self) -> list[dict[str, Any]]:
        """Все задачи рабочей памяти со сводкой, свежие сверху."""
        итог = []
        for имя in sorted(os.listdir(self.directory)):
            if not имя.endswith(".json"):
                continue
            try:
                состояние = self.load(имя[:-5])
            except WorkingMemoryError:
                continue
            итог.append(
                {
                    "task_id": состояние.task_id,
                    "title": состояние.title,
                    "stage": состояние.stage,
                    "stage_label": состояние.stage_label,
                    "plan_steps": len(состояние.plan),
                    "collected": len(состояние.collected),
                    "updated_at": состояние.updated_at,
                    "пауза": состояние.пауза,
                    "причина_паузы": состояние.причина_паузы,
                    "ожидание": состояние.ожидание,
                    "ожидание_текст": состояние.ожидание_текст,
                    "шаг": состояние.текущий_шаг,
                    "шагов": состояние.шагов,
                    "сценарий": состояние.сценарий,
                }
            )
        итог.sort(key=lambda з: з["updated_at"], reverse=True)
        return итог

    def drop(self, task_id: str) -> bool:
        """Убирает задачу из рабочей памяти.

        Вызывается после того, как итог задачи свёрнут в журнал решений: рабочая
        память — не архив, и держать в ней завершённое незачем.
        """
        try:
            os.remove(self._path(task_id))
            return True
        except FileNotFoundError:
            return False
