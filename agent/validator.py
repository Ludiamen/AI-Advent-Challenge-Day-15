# Обороты, где между словами вклинивается предмет сравнения: «чем PostGIS лучше
# MySQL». Подстрокой такое не поймать, поэтому отдельным выражением.
ВОПРОС_ВЫРАЖЕНИЯ = (
    re.compile(r"\bчем\b.{0,40}\b(лучше|хуже|плох|удобнее|быстрее)", re.IGNORECASE),
    re.compile(r"\bв\s+ч[её]м\b.{0,40}\b(разница|отличие|преимуществ)", re.IGNORECASE),
)


def _похоже_на_вопрос(низ: str) -> bool:
    return (any(признак in низ for признак in ВОПРОС)
            or any(в.search(низ) for в in ВОПРОС_ВЫРАЖЕНИЯ))

# Формат закреплён в prompts: и промпт, и разбор должны говорить об одном и том
# же, иначе агент отчитывается одним способом, а код ищет другой.
МАРКЕР_САМООТЧЁТА = prompts.МАРКЕР_САМООТЧЁТА

_БЛОК_КОДА = re.compile(r"```.*?```", re.DOTALL)
_СЛОВО = re.compile(r"[a-zA-Zа-яёА-ЯЁ0-9_]{4,}")

# Слова, которые ничего не говорят о теме и только мешают определять, какой
# инвариант применим к запросу.
_ШУМ = {
    "который", "которая", "которые", "чтобы", "если", "тогда", "потом", "также",
    "нужно", "надо", "быть", "есть", "этот", "эта", "это", "того", "тому",
    "можно", "нельзя", "очень", "более", "менее", "только", "самый", "нашей",
    "нашего", "наших", "нового", "новой", "новые", "сделай", "напиши",
}


# Кириллические и латинские буквы, неразличимые на вид. Модель, перечисляя коды
# инвариантов, регулярно печатает «1c» латинской c вместо кириллической — и
# самоотчёт, который человек читает как полный, код считает неполным.
_ОМОГЛИФЫ = str.maketrans({
    "c": "с", "a": "а", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у",
    "k": "к", "b": "ь", "m": "м", "h": "н", "t": "т",
})


def _сличить(код: str) -> str:
    """Приводит код к виду, в котором омоглифы не мешают сравнению."""
    return (код or "").strip().lower().translate(_ОМОГЛИФЫ)


def _слова(текст: str) -> set[str]:
    return {с.lower() for с in _СЛОВО.findall(текст or "")} - _ШУМ


@dataclass
class Violation:
    """Одно нарушение: какой инвариант, что нашли, почему так решено."""

    код: str
    правило: str
    вид: str = ""
    найдено: str = ""
    где: str = ""                # «запрос» | «текст» | «код» | «смысл» | «самоотчёт»
    фрагмент: str = ""
    почему: str = ""             # обоснование инварианта — идёт в отказ
    вместо: str = ""             # допустимая альтернатива

    def __str__(self) -> str:
        часть = self.правило
        if self.найдено:
            часть += f" (найдено «{self.найдено}» в {self.где})"
        return часть

    def to_dict(self) -> dict[str, Any]:
        return {
            "код": self.код, "правило": self.правило, "вид": self.вид,
            "найдено": self.найдено, "где": self.где, "фрагмент": self.фрагмент,
            "почему": self.почему, "вместо": self.вместо,
        }


@dataclass
class Refusal:
    """Формализованный отказ. Составляется кодом, поэтому одинаков всегда."""

    нарушения: list[Violation] = field(default_factory=list)
    когда: str = "до вызова"      # «до вызова» | «после ответа»
    запрос: str = ""

    @property
    def есть(self) -> bool:
        return bool(self.нарушения)

    def текст(self) -> str:
        """Отказ словами: что нельзя, какой инвариант, почему и что вместо."""
        if not self.нарушения:
            return ""
        строки = ["Не могу этого предложить: это нарушило бы инварианты проекта."]
        for н in self.нарушения:
            строки.append("")
            заголовок = f"• {н.правило}"
            if н.вид:
                заголовок += f"  [{н.вид}, код «{н.код}»]"
            строки.append(заголовок)
            if н.почему:
                строки.append(f"  Почему так решено: {н.почему}")
            if н.найдено and н.где:
                строки.append(f"  Что именно не проходит: «{н.найдено}» в {н.где}.")
            if н.вместо:
                строки.append(f"  Что можно вместо: {н.вместо}")
        строки.append("")
        строки.append(
            "Инварианты — не мои предпочтения, а решения проекта: они записаны "
            "отдельно от разговора и не меняются по ходу переписки. Если решение "
            "устарело, его нужно сначала пересмотреть и снять инвариант — "
            "тогда изменится и мой ответ."
        )
        if self.когда == "до вызова":
            строки.append(
                "Запрос отклонён до обращения к модели, поэтому токены не потрачены."
            )
        return "\n".join(строки)

    def to_dict(self) -> dict[str, Any]:
        return {
            "есть": self.есть,
            "когда": self.когда,
            "нарушения": [н.to_dict() for н in self.нарушения],
            "текст": self.текст(),
        }


