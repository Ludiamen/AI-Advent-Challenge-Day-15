"""Проверка инвариантов: кодом там, где можно, смыслом там, где нельзя.

На лекции это сказано прямо: текстового инварианта в промпте недостаточно.
Модель — вежливый собеседник, и на настойчивую просьбу «ну сделай на Laravel»
она согласится, несмотря на системный промпт. Код не согласится.

Здесь три рубежа, и они отвечают на разные вопросы.

  1. ЗАПРОС до обращения к модели. «Перепиши слой доступа на Laravel» — это
     требование нарушить инвариант, и отвечать на него не нужно вовсе: отказ
     формируется сразу, без единого потраченного токена. Отличать требование от
     вопроса обязательно: «а почему нельзя Laravel?» — законный вопрос, на
     который надо ответить по существу.

  2. ОТВЕТ после обращения. Запрос мог быть невинным, а ответ — нет. Жёсткие
     инварианты ищутся в тексте: слова, вызовы API в блоках кода, выражения.

  3. СМЫСЛ — для того, что регуляркой не выражается: архитектура, бизнес-правила,
     принятые решения. Два независимых рубежа: агент обязан закончить ответ
     самоотчётом «УЧТЕНЫ ИНВАРИАНТЫ: …», и код сверяет его полноту с тем, что
     сам считает применимым; плюс дешёвая модель судит по сути. Первый рубеж
     детерминирован, но проверяет лишь упоминание; второй понимает смысл, но
     недетерминирован. Порознь каждого мало.

Отказ формирует КОД, а не модель. Поэтому он одинаков при каждом конфликте,
называет конкретный инвариант, его обоснование и допустимую альтернативу — всё
это заранее записано в самом инварианте.

Публичное API:
  Violation                        — одно нарушение
  Refusal                          — формализованный отказ
  JudgeResult                      — вердикт проверяющей модели
  StateValidator(...)              — все три рубежа
  МАРКЕР_САМООТЧЁТА                — как агент перечисляет учтённое
"""

