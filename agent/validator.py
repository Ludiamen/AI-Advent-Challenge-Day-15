class StateValidator:
    """Три рубежа проверки инвариантов плюс проверка переходов задачи."""

    def __init__(
        self,
        invariants: Callable[[], list[Invariant]],
        client: Client | None = None,
        judge_model: str = "",
    ) -> None:
        # Инварианты берутся вызовом, а не списком: их правят посреди разговора,
        # и слепок, снятый при создании, однажды окажется вчерашним.
        self._invariants = invariants
        self.client = client
        self.judge_model = judge_model

    # --- словарь -------------------------------------------------------------

    def all(self) -> list[Invariant]:
        return self._invariants()

    def hard(self) -> list[Invariant]:
        return [и for и in self.all() if и.жёсткий]

    def semantic(self) -> list[Invariant]:
        return [и for и in self.all() if not и.жёсткий]

    def applicable(self, *тексты: str) -> list[Invariant]:
        """Какие инварианты имеют отношение к этому запросу.

        Жёсткие применимы всегда: их всё равно проверяет код, и назвать их в
        самоотчёте ничего не стоит. Смысловые отбираются по пересечению слов —
        требовать самоотчёт по бизнес-правилу про 1С в ответе про вёрстку карты
        значило бы приучать агента писать «учтено» не глядя.
        """
        слова = set()
        for текст in тексты:
            слова |= _слова(текст)
        итог = []
        for инвариант in self.all():
            if инвариант.жёсткий:
                итог.append(инвариант)
                continue
            свои = _слова(инвариант.правило) | {з.lower() for з in инвариант.значения}
            if слова & свои:
                итог.append(инвариант)
        return итог

    # --- рубеж 1: запрос -----------------------------------------------------

    def check_request(self, запрос: str) -> list[Violation]:
        """Требует ли сам запрос нарушить инвариант.

        Отказ до обращения к модели экономит не только токены: он честнее.
        «Отказываюсь предлагать» и «предложил, потом сам себя отругал» — разные
        вещи, и второе пользователь видит как непоследовательность.
        """
        текст = (запрос or "").strip()
        if not текст:
            return []
        низ = текст.lower()
        # Вопрос об инварианте — не нарушение. Агент обязан уметь объяснить свои
        # ограничения, иначе он не помощник, а вахтёр.
        if _похоже_на_вопрос(низ):
            return []
        if not any(признак in низ for признак in ПОВЕЛЕНИЕ):
            return []

        нарушения: list[Violation] = []
        for инвариант in self.hard():
            if инвариант.тип == ЗАПРЕТ_РЕГУЛЯРОК:
                # Выражения описывают вид ответа (секрет в URL), а не просьбу.
                continue
            for значение in инвариант.значения:
                позиция = _найти(текст, значение)
                if позиция is None or _отрицание_в_запросе(текст, позиция):
                    continue
                нарушения.append(Violation(
                    код=инвариант.код, правило=инвариант.правило, вид=инвариант.вид,
                    найдено=значение, где="запросе",
                    фрагмент=_вырезка(текст, позиция),
                    почему=инвариант.почему, вместо=инвариант.вместо,
                ))
                break
        return нарушения

    # --- рубеж 2: ответ ------------------------------------------------------

    def is_explanatory(self, запрос: str) -> bool:
        """Спрашивают ли о самом инварианте, а не требуют его нарушить.

        Различие важное. Объясняя, почему проект не на Laravel, агент обязан
        называть Laravel — иначе объяснения не выйдет. Проверка прозы на таком
        ответе срабатывает ложно, и агент отказывается объяснять собственные
        ограничения, превращаясь в вахтёра. На живом прогоне именно это и
        случилось: «а почему у нас нельзя Laravel?» получило отказ.
        """
        низ = (запрос or "").lower()
        if not _похоже_на_вопрос(низ):
            return False
        return any(
            _найти(низ, значение) is not None
            for инвариант in self.hard()
            for значение in инвариант.значения
        )

    def check(self, answer: str, explanatory: bool = False) -> list[Violation]:
        """Ищет нарушения жёстких инвариантов в ответе. Модель не участвует.

        explanatory=True — ответ объясняет сам инвариант. Тогда упоминания в
        прозе не проверяются: они и есть содержание ответа. Блоки кода и
        выражения проверяются всегда — объяснять можно, писать код на
        запрещённом стеке нельзя и в объяснении.
        """
        нарушения: list[Violation] = []
        текст = answer or ""
        куски_кода = _БЛОК_КОДА.findall(текст)
        проза = "" if explanatory else _БЛОК_КОДА.sub(" ", текст)

        for инвариант in self.hard():
            for значение in инвариант.значения:
                найдено = self._искать(инвариант, значение, текст, проза, куски_кода)
                if найдено is not None:
                    нарушения.append(найдено)
                    break
        return нарушения

    @staticmethod
    def _искать(инвариант: Invariant, значение: str, текст: str, проза: str,
                куски_кода: list[str]) -> Violation | None:
        def нарушение(где: str, откуда: str, позиция: int) -> Violation:
            return Violation(
                код=инвариант.код, правило=инвариант.правило, вид=инвариант.вид,
                найдено=значение, где=где, фрагмент=_вырезка(откуда, позиция),
                почему=инвариант.почему, вместо=инвариант.вместо,
            )

        if инвариант.тип == ЗАПРЕТ_СЛОВ:
            # В коде запрещённое слово означает именно использование — никаких
            # поблажек на контекст.
            for кусок in куски_кода:
                позиция = _найти(кусок, значение)
                if позиция is not None:
                    return нарушение("коде", кусок, позиция)
            позиция = _найти(проза, значение)
            if позиция is not None and not _отрицание(проза, позиция):
                return нарушение("тексте", проза, позиция)
            return None

        if инвариант.тип == ЗАПРЕТ_В_КОДЕ:
            # Упоминание legacy-компонента обязательно по профилю, а вот код на
            # нём — уже нарушение. Смотрим только в блоки кода.
            for кусок in куски_кода:
                позиция = _найти(кусок, значение)
                if позиция is not None:
                    return нарушение("коде", кусок, позиция)
            return None

        if инвариант.тип == ЗАПРЕТ_РЕГУЛЯРОК:
            совпадение = re.compile(значение, re.IGNORECASE).search(текст)
            if совпадение:
                итог = нарушение("ответе", текст, совпадение.start())
                итог.найдено = совпадение.group(0)
                return итог
        return None

    # --- рубеж 3: смысл ------------------------------------------------------

    @staticmethod
    def self_report(answer: str) -> list[str]:
        """Достаёт коды инвариантов из самоотчёта агента.

        Смотрим и в начало, и в конец. Требовать самоотчёт только последней
        строкой оказалось нежизнеспособно: длинный ответ упирается в предел
        токенов, обрывается на полуслове, и строки просто не существует.
        Первая строка от обрезки не страдает.
        """
        строки = [с.strip() for с in (answer or "").strip().split("\n") if с.strip()]
        for строка in строки[:4] + строки[-6:][::-1]:
            без = строка.lstrip("*_#> ").strip()
            if без.upper().startswith(МАРКЕР_САМООТЧЁТА):
                хвост = без[len(МАРКЕР_САМООТЧЁТА):]
                # Коды перечисляются через запятую, у каждого может быть
                # пояснение в скобках — его отбрасываем.
                коды = []
                for кусок in re.split(r"[,;]", хвост):
                    имя = re.sub(r"\(.*?\)", "", кусок).strip(" *_`.")
                    if имя:
                        коды.append(имя.lower())
                return коды
        return []

    def check_self_report(self, answer: str, применимые: list[Invariant]) -> list[str]:
        """Каких применимых инвариантов нет в самоотчёте.

        Пустой список означает «самоотчёт полон». Если применимых инвариантов
        нет вовсе, требовать самоотчёт незачем.
        """
        if not применимые:
            return []
        названные = {_сличить(к) for к in self.self_report(answer)}
        if not названные:
            return [и.код for и in применимые]
        return [и.код for и in применимые if _сличить(и.код) not in названные]

    def judge(self, answer: str, применимые: list[Invariant]) -> JudgeResult:
        """Просит дешёвую модель судить о смысловых инвариантах.

        Проверяющий видит только правила и ответ — ни запроса пользователя, ни
        уговоров. Так его труднее склонить: склонять нечем.
        """
        смысловые = [и for и in применимые if not и.жёсткий]
        if not смысловые:
            return JudgeResult()
        if self.client is None:
            return JudgeResult(сбой=True, пояснения={"": "модель для проверки не задана"})

        from agent import catalog
        ключ = self.judge_model or catalog.for_role("судья-инвариантов")
        правила = "\n".join(f"[{и.код}] {и.правило}" for и in смысловые)
        сообщения = [
            {"role": "system", "content": prompts.JUDGE},
            {"role": "user",
             "content": f"ИНВАРИАНТЫ:\n{правила}\n\nОТВЕТ АГЕНТА:\n{answer[:3500]}"},
        ]
        # Проверяющие модели самые слабые, и пустой ответ от них — обычное
        # дело. Поднимаемся на одну ступень, как это делает маршрутизатор: без
        # этого смысловые инварианты остаются без проверки вовсе, а выглядит
        # это как «нарушений нет».
        данные = None
        for попытка in range(2):
            try:
                ответ = self.client.call(ключ, сообщения, max_tokens=400,
                                         temperature=0.0, low_effort=True)
            except LLMError as exc:
                log.warning("Проверяющая модель недоступна (%s): %s", ключ, exc)
                причина = str(exc)[:120]
            else:
                данные = _разобрать_json(ответ.text)
                if данные is not None:
                    break
                log.warning("Проверяющая модель %s вернула неразбираемый вердикт", ключ)
                причина = "вердикт не разобрался"
            if попытка == 0:
                следующая = catalog.escalate(ключ)
                if следующая != ключ:
                    ключ = следующая
                    continue
            break

        if данные is None:
            return JudgeResult(модель=ключ, сбой=True, пояснения={"": причина})
        известные = {и.код.lower(): и.код for и in смысловые}
        нарушены, пояснения = [], {}
        for запись in данные.get("нарушены") or []:
            код = str(запись.get("код", "")).strip().lower() if isinstance(запись, dict) \
                else str(запись).strip().lower()
            if код in известные:
                нарушены.append(известные[код])
                if isinstance(запись, dict):
                    пояснения[известные[код]] = str(запись.get("почему", ""))
        return JudgeResult(нарушены=нарушены, пояснения=пояснения, модель=ключ)

    def violations_from_judge(self, вердикт: JudgeResult) -> list[Violation]:
        """Превращает вердикт модели в нарушения — с обоснованием из инварианта."""
        по_коду = {и.код: и for и in self.all()}
        итог = []
        for код in вердикт.нарушены:
            инвариант = по_коду.get(код)
            if инвариант is None:
                continue
            итог.append(Violation(
                код=инвариант.код, правило=инвариант.правило, вид=инвариант.вид,
                найдено=вердикт.пояснения.get(код, "")[:120], где="смысле ответа",
                почему=инвариант.почему, вместо=инвариант.вместо,
            ))
        return итог

    # --- отказ и напоминания -------------------------------------------------

    @staticmethod
    def refusal(нарушения: list[Violation], когда: str = "до вызова",
                запрос: str = "") -> Refusal:
        return Refusal(нарушения=list(нарушения), когда=когда, запрос=запрос)

    def reminder(self, violations: list[Violation]) -> str:
        перечень = "; ".join(str(н) for н in violations)
        return REMINDER.format(нарушения=перечень)

    @staticmethod
    def self_report_reminder(пропущено: list[str]) -> str:
        return НАПОМИНАНИЕ_САМООТЧЁТА.format(
            маркер=МАРКЕР_САМООТЧЁТА, пропущено=", ".join(пропущено))

    # --- переходы задачи -----------------------------------------------------

    @staticmethod
    def check_transition(state: TaskState, stage: str) -> tuple[bool, str]:
        """Допустим ли переход. Сам переход не делает — только выносит вердикт."""
        try:
            копия = TaskState.from_dict(state.to_dict())
            копия.transition(stage)
        except TransitionError as exc:
            return False, str(exc)
        return True, f"переход {state.stage} -> {stage} разрешён"


def _найти(text: str, слово: str) -> int | None:
    """Ищет слово целиком, без учёта регистра; возвращает позицию или None."""
    выражение = re.compile(rf"(?<![\w.]){re.escape(слово)}(?![\w])", re.IGNORECASE)
    совпадение = выражение.search(text)
    return совпадение.start() if совпадение else None


# Отрицание в ЗАПРОСЕ устроено иначе, чем в ответе, и путать их нельзя. В
# ответе «вместо» рядом с запрещённым словом почти всегда означает отказ от
# него: «вместо Laravel берём Django». В запросе — наоборот: «возьмём MySQL
# вместо PostGIS» означает, что MySQL и есть цель. На этом проверка запроса и
# промахнулась на живом прогоне, пропустив прямое требование сменить СУБД.
_СЛЕВА = ("не ", "без ", "вместо ", "кроме ", "отказ", "убери ", "убрать ")
_СПРАВА = ("не ", "нельзя", "убрать", "убери", "запрещ")


def _отрицание_в_запросе(text: str, позиция: int, слово_длина: int = 0) -> bool:
    """Отказывается ли сам запрос от найденного слова.

    Слева смотрим шире: «вместо Laravel возьмём Django» — отказ. Справа уже и
    без «вместо»: «Laravel не использовать» — отказ, а «MySQL вместо PostGIS» —
    требование.
    """
    слева = text[max(0, позиция - 30):позиция].lower()
    справа = text[позиция:позиция + 40].lower()
    # Отрезаем само слово, иначе «не» внутри него сработает ложно.
    справа = справа[справа.find(" "):] if " " in справа else ""
    return (any(м in слева for м in _СЛЕВА)
            or any(справа.lstrip().startswith(м) for м in _СПРАВА))


def _отрицание(text: str, позиция: int) -> bool:
    """Есть ли рядом с найденным словом признак отказа от него."""
    начало = max(0, позиция - WINDOW)
    окно = text[начало:позиция + WINDOW].lower()
    return any(маркер in окно for маркер in NEGATIONS)


def _вырезка(text: str, позиция: int, ширина: int = 70) -> str:
    начало = max(0, позиция - ширина // 2)
    кусок = text[начало:позиция + ширина].replace("\n", " ").strip()
    return ("…" if начало else "") + кусок + "…"


def _разобрать_json(текст: str) -> dict[str, Any] | None:
    """Достаёт вердикт из ответа модели, даже если он завёрнут в markdown."""
    строка = (текст or "").strip()
    в_ограждении = re.search(r"```(?:json)?\s*(.+?)\s*```", строка, re.DOTALL)
    if в_ограждении:
        строка = в_ограждении.group(1).strip()
    начало, конец = строка.find("{"), строка.rfind("}")
    if начало == -1 or конец <= начало:
        return None
    try:
        данные = json.loads(строка[начало:конец + 1])
    except json.JSONDecodeError:
        return None
    return данные if isinstance(данные, dict) else None
