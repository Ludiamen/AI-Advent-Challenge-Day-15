class ConditionStore:
    """Личные условия перехода: файл рядом с профилем пользователя."""

    layer = "долговременная"
    sublayer = "условия переходов"

    def __init__(self, path: str) -> None:
        self.path = path

    def all(self) -> list[Условие]:
        try:
            with open(self.path, encoding="utf-8") as файл:
                данные = json.load(файл)
        except FileNotFoundError:
            return []
        except (OSError, json.JSONDecodeError) as exc:
            raise TransitionConfigError(
                f"Файл условий перехода «{self.path}» испорчен: {exc}") from exc
        if not isinstance(данные, list):
            return []
        return [Условие.from_dict(у) for у in данные]

    def save_all(self, условия: list[Условие]) -> None:
        временный = self.path + ".tmp"
        try:
            os.makedirs(os.path.dirname(os.path.abspath(self.path)), exist_ok=True)
            with open(временный, "w", encoding="utf-8") as файл:
                json.dump([у.to_dict() for у in условия], файл,
                          ensure_ascii=False, indent=2)
            os.replace(временный, self.path)
        except OSError as exc:
            raise TransitionConfigError(f"Не удалось записать условия: {exc}") from exc

    def get(self, код: str) -> Условие | None:
        код = (код or "").strip().lower()
        for условие in self.all():
            if условие.код.lower() == код:
                return условие
        return None

    def add(self, условие: Условие) -> Условие:
        условие.уровень = ЛИЧНЫЙ
        условие.validate()
        if any(б.код.lower() == условие.код.lower() for б in БАЗОВЫЕ):
            # Совпадение кода — единственный способ подменить базовое условие
            # своим, и именно поэтому он закрыт.
            raise TransitionConfigError(
                f"Код «{условие.код}» занят базовым условием жизненного цикла. "
                "Базовые условия не переопределяются — возьмите другой код."
            )
        остальные = [у for у in self.all() if у.код.lower() != условие.код.lower()]
        остальные.append(условие)
        self.save_all(остальные)
        return условие

    def remove(self, код: str) -> bool:
        было = self.all()
        осталось = [у for у in было if у.код.lower() != (код or "").strip().lower()]
        if len(осталось) == len(было):
            return False
        self.save_all(осталось)
        return True


def merge(базовые: list[Условие], личные: list[Условие]) -> list[Условие]:
    """Общий набор условий. Личное добавляет требований, но не снимает базовых."""
    итог: list[Условие] = []
    занятые: set[str] = set()
    for условие in базовые:
        условие.уровень = БАЗОВЫЙ
        итог.append(условие)
        занятые.add(условие.код.lower())
    for условие in личные:
        if условие.код.lower() in занятые:
            continue
        условие.уровень = ЛИЧНЫЙ
        итог.append(условие)
    return итог


