# --- кто просит переход -------------------------------------------------------
ЧЕЛОВЕК = "человек"
МОДЕЛЬ = "модель"
СЦЕНАРИЙ = "сценарий"
КОД = "код"
ИСТОЧНИКИ = (ЧЕЛОВЕК, МОДЕЛЬ, СЦЕНАРИЙ, КОД)

# --- чем проверяется условие --------------------------------------------------
ПЛАН_УТВЕРЖДЁН = "план-утверждён"
ПЛАН_НЕ_ПУСТ = "план-не-пуст"
ШАГИ_ПРОЙДЕНЫ = "шаги-пройдены"
ВАЛИДАЦИЯ_ПРОЙДЕНА = "валидация-пройдена"
ЕСТЬ_В_СОБРАННОМ = "есть-в-собранном"
НЕТ_ОТКРЫТЫХ_ВОПРОСОВ = "нет-открытых-вопросов"
ПРОВЕРКИ = (ПЛАН_УТВЕРЖДЁН, ПЛАН_НЕ_ПУСТ, ШАГИ_ПРОЙДЕНЫ, ВАЛИДАЦИЯ_ПРОЙДЕНА,
            ЕСТЬ_В_СОБРАННОМ, НЕТ_ОТКРЫТЫХ_ВОПРОСОВ)

ПРОВЕРКИ_СЛОВАМИ = {
    ПЛАН_УТВЕРЖДЁН: "план составлен и подписан человеком",
    ПЛАН_НЕ_ПУСТ: "в плане не меньше указанного числа пунктов",
    ШАГИ_ПРОЙДЕНЫ: "все шаги задачи доведены до конца",
    ВАЛИДАЦИЯ_ПРОЙДЕНА: "отчёт проверки собран и в нём нет красных пунктов",
    ЕСТЬ_В_СОБРАННОМ: "в собранных данных есть запись с указанным ключом",
    НЕТ_ОТКРЫТЫХ_ВОПРОСОВ: "задача не ждёт ответа человека",
}

# --- уровни -------------------------------------------------------------------
БАЗОВЫЙ = "базовый"
ЛИЧНЫЙ = "личный"
УРОВНИ = (БАЗОВЫЙ, ЛИЧНЫЙ)

# --- причины отказа -----------------------------------------------------------
НЕТ_СТРЕЛКИ = "в жизненном цикле нет такого перехода"
НЕ_ВЫПОЛНЕНО = "условие перехода не выполнено"
НЕТ_СТАДИИ = "неизвестная стадия"
НА_ПАУЗЕ = "задача на паузе"

ЛЮБАЯ = "*"

МАРКЕР_ПЕРЕХОДА = prompts.МАРКЕР_ПЕРЕХОДА
_МАРКЕР = re.compile(rf"^\s*{МАРКЕР_ПЕРЕХОДА}\s*([a-zA-Z\-]+)\s*$", re.MULTILINE)

_КОД = re.compile(r"^[a-zA-Zа-яёА-ЯЁ0-9][a-zA-Zа-яёА-ЯЁ0-9_\-]{0,47}$")


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


class TransitionConfigError(ValueError):
    """Негодное описание условия перехода."""


# --- условие ------------------------------------------------------------------

@dataclass
class Условие:
    """Одно условие перехода: когда применяется, что требует и как открывается."""

    код: str
    откуда: str = ЛЮБАЯ           # стадия-источник или «*»
    куда: str = ЛЮБАЯ             # стадия-цель или «*»
    что: str = ПЛАН_УТВЕРЖДЁН     # чем проверяется
    значение: str = ""            # параметр проверки: ключ, число
    правило: str = ""             # формулировка словами — идёт в отказ
    почему: str = ""              # обоснование — тоже идёт в отказ
    вместо: str = ""              # что сделать, чтобы условие выполнилось
    уровень: str = ЛИЧНЫЙ
    создан: str = field(default_factory=_now)

    def validate(self) -> None:
        if not _КОД.match(self.код or ""):
            raise TransitionConfigError(
                f"Негодный код условия «{self.код}»: нужны буквы, цифры, дефис "
                "и подчёркивание, до 48 символов."
            )
        for поле, значение in (("откуда", self.откуда), ("куда", self.куда)):
            if значение != ЛЮБАЯ and значение not in STAGES:
                raise TransitionConfigError(
                    f"Условие «{self.код}»: неизвестная стадия в поле {поле} — "
                    f"«{значение}». Допустимы: {', '.join(STAGES)} или «{ЛЮБАЯ}»."
                )
        if self.что not in ПРОВЕРКИ:
            raise TransitionConfigError(
                f"Условие «{self.код}»: неизвестная проверка «{self.что}». "
                f"Допустимы: {', '.join(ПРОВЕРКИ)}."
            )
        if self.что == ЕСТЬ_В_СОБРАННОМ and not (self.значение or "").strip():
            # Проверка без параметра проверяет пустоту и всегда проходит — это
            # хуже отсутствующего условия: создаёт ложное чувство контроля.
            raise TransitionConfigError(
                f"Условие «{self.код}»: для проверки «{ЕСТЬ_В_СОБРАННОМ}» нужен "
                "ключ, который должен найтись в собранных данных."
            )
        if self.что == ПЛАН_НЕ_ПУСТ:
            try:
                if int(self.значение or 1) < 1:
                    raise ValueError
            except ValueError:
                raise TransitionConfigError(
                    f"Условие «{self.код}»: для проверки «{ПЛАН_НЕ_ПУСТ}» нужно "
                    "целое число пунктов, не меньше единицы."
                ) from None
        if not (self.правило or "").strip():
            raise TransitionConfigError(f"Условие «{self.код}» без формулировки правила.")
        if self.уровень not in УРОВНИ:
            raise TransitionConfigError(
                f"Условие «{self.код}»: неизвестный уровень «{self.уровень}»."
            )

    def подходит(self, откуда: str, куда: str) -> bool:
        """Применяется ли условие к этому переходу."""
        return ((self.откуда in (ЛЮБАЯ, откуда))
                and (self.куда in (ЛЮБАЯ, куда))
                # Условие «на любой переход» не должно срабатывать на переходе
                # в ту же стадию: это не переход, а его отсутствие.
                and откуда != куда)

    def проверить(self, state: TaskState) -> tuple[bool, str]:
        """Выполнено ли условие. Второе значение — что видно в состоянии сейчас."""
        if self.что == ПЛАН_УТВЕРЖДЁН:
            if not state.plan:
                return False, "плана нет — задача не проходила стадию планирования"
            if not state.план_утверждён:
                return False, f"план из {len(state.plan)} пунктов никто не утверждал"
            if not state.утверждение_актуально:
                подпись = state.план_утверждён
                return False, (f"план правили после утверждения (подписан "
                               f"{подпись.get('когда', '?')}) — нужно утвердить заново")
            подпись = state.план_утверждён
            return True, (f"утвердил {подпись.get('кем', '?')}, "
                          f"{подпись.get('когда', '?')}, пунктов {len(state.plan)}")
        if self.что == ПЛАН_НЕ_ПУСТ:
            нужно = int(self.значение or 1)
            если_есть = len(state.plan)
            if если_есть < нужно:
                return False, f"пунктов в плане {если_есть}, нужно не меньше {нужно}"
            return True, f"пунктов в плане {если_есть}"
        if self.что == ШАГИ_ПРОЙДЕНЫ:
            if not state.шаги:
                return False, "шагов нет: план не превратился в шаги задачи"
            # Считаются шаги ТЕКУЩЕЙ стадии, а не все подряд. Задача по сценарию
            # держит в одном списке шаги всех стадий, и «все шаги пройдены»
            # означало бы, что стадию исполнения нельзя закрыть, пока не сделан
            # шаг ревьюера, который сам живёт на стадии проверки. Условие тогда
            # запирало бы сценарий на его же последнем шаге.
            свои = [ш for ш in state.шаги if ш.стадия == state.stage] or list(state.шаги)
            осталось = [ш for ш in свои if ш.состояние != ГОТОВ]
            if осталось:
                имена = ", ".join(f"{ш.номер}. {ш.имя}" for ш in осталось[:3])
                хвост = f" и ещё {len(осталось) - 3}" if len(осталось) > 3 else ""
                return False, f"не доведены шаги стадии «{state.stage}»: {имена}{хвост}"
            return True, f"пройдены все шаги стадии «{state.stage}» ({len(свои)})"
        if self.что == ВАЛИДАЦИЯ_ПРОЙДЕНА:
            отчёт = state.отчёт_валидации or {}
            if not отчёт:
                return False, "отчёта проверки нет — задача не проходила валидацию"
            # Красное — только явное «не прошло». Пункт «не проверено» (ревизор
            # не ответил) в отчёте виден, но переход не запирает: см. подробнее
            # MemoryAgent.validate_task.
            красные = [п for п in отчёт.get("пункты", []) if п.get("итог") == "не прошло"]
            if красные:
                перечень = "; ".join(п.get("пункт", "?") for п in красные[:3])
                return False, f"в отчёте проверки не пройдено: {перечень}"
            if not state.валидация_актуальна:
                return False, ("работа менялась после проверки — отчёт устарел, "
                               "нужна повторная валидация")
            return True, (f"проверка пройдена {отчёт.get('когда', '?')}, "
                          f"пунктов {len(отчёт.get('пункты', []))}")
        if self.что == ЕСТЬ_В_СОБРАННОМ:
            ключ = (self.значение or "").strip().lower()
            for имя in state.collected:
                if ключ in имя.lower():
                    return True, f"найдено в собранном: «{имя}»"
            return False, f"в собранных данных нет записи про «{self.значение}»"
        if self.что == НЕТ_ОТКРЫТЫХ_ВОПРОСОВ:
            if state.ожидание == ОТВЕТ:
                return False, f"задача ждёт ответа: {state.ожидание_текст or 'вопрос задан'}"
            return True, "открытых вопросов нет"
        return True, "проверка неизвестна — условие пропущено"

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Условие":
        известные = {поле for поле in cls.__dataclass_fields__}
        return cls(**{к: з for к, з in data.items() if к in известные})

    def digest(self) -> str:
        стрелка = f"{self.откуда} → {self.куда}"
        return f"{self.код:<26} {стрелка:<26} {self.что:<22} {self.уровень}"


