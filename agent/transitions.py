"""Контролируемые переходы: стадию меняет выполненное условие, а не намерение.

В прошлом дне у задачи уже был конечный автомат: четыре стадии и явный список
разрешённых стрелок. Этого оказалось мало, и изъян виден на одном примере.
Переход planning -> execution в списке есть, поэтому он проходил ВСЕГДА — в том
числе когда плана не было вовсе. То есть автомат проверял форму маршрута, но не
проверял, заслужен ли шаг. «Нельзя делать реализацию до утверждённого плана» при
таком автомате остаётся благим пожеланием.

Поэтому у перехода теперь две проверки, и они разной природы:

  1. СТРЕЛКА   есть ли такой переход в жизненном цикле вообще (TRANSITIONS);
  2. УСЛОВИЕ   выполнено ли то, ради чего этап существует (этот модуль).

Условие — это не текст в промпте и не договорённость с моделью. Это функция от
состояния задачи, которую выполняет код: план подписан человеком, все шаги
пройдены, отчёт проверки собран и в нём нет красных пунктов. Модель может
сколько угодно писать «задача готова» — стадия от этого не изменится.

Уровня у условий два, как и у инвариантов в прошлом дне:

  БАЗОВЫЕ  живут здесь, в коде, и снять их нельзя: это костяк жизненного цикла,
           ровно те два примера, что названы в задании, плюс два очевидных;
  ЛИЧНЫЕ   живут файлом рядом с профилем и добавляются пользователем под свой
           процесс («в готово — только когда в собранном есть ссылка на
           репозиторий»). Личное может ужесточить, но не ослабить базовое.

Просить переход может четверо, и разница между ними существенна для разбора
полётов, поэтому источник попытки записывается:

  человек    команда CLI или кнопка на странице;
  модель     строка «ПЕРЕХОД: done» в ответе — единственный способ, которым
             ассистенту вообще позволено влиять на стадию;
  сценарий   очередной шаг требует другой стадии;
  код        служебные переводы (свёртка задачи).

Отклонённая попытка не исчезает: она ложится в состояние задачи отдельным
журналом. Без этого «ассистент не смог перепрыгнуть этап» пришлось бы принимать
на веру — а так его попытка и причина отказа лежат в файле задачи.

Публичное API:
  ИСТОЧНИКИ, ПРОВЕРКИ, УРОВНИ        — словарь предметной области
  Условие                            — одно условие перехода
  БАЗОВЫЕ                            — несъёмный костяк
  ConditionStore(path)               — личные условия пользователя
  merge(базовые, личные)             — общий набор
  Ворота(условия)                    — проверка и выполнение перехода
  Вердикт, ОтказПерехода             — результат проверки и отказ словами
  просьба(text) / убрать_маркер(text) — канал «модель просит переход»
"""

from __future__ import annotations

import json
import os
import re
from collections import deque
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, Callable

from agent import prompts
