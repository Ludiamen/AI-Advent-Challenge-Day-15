@dataclass
class Проверка:
    """Итог одного условия на конкретном переходе."""

    код: str
    правило: str
    выполнено: bool
    видно: str = ""              # что показывает состояние задачи сейчас
    почему: str = ""
    вместо: str = ""
    уровень: str = БАЗОВЫЙ

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    def __str__(self) -> str:
        знак = "✓" if self.выполнено else "✗"
        return f"{знак} {self.код}: {self.видно}"


@dataclass
class ОтказПерехода:
    """Отказ в переходе. Составляется кодом, поэтому одинаков при каждой попытке."""

    откуда: str
    куда: str
    кто: str = ЧЕЛОВЕК
    причина: str = НЕ_ВЫПОЛНЕНО
    проверки: list[Проверка] = field(default_factory=list)
    разрешено: list[str] = field(default_factory=list)
    маршрут: list[str] = field(default_factory=list)
    # Ближайший законный шаг вместе с его собственным вердиктом. Без него отказ
    # советует «идите через исполнение», умалчивая, что исполнение тоже заперто,
    # и человек упирается во вторую стену сразу после первой.
    следующий: dict[str, Any] = field(default_factory=dict)
    когда: str = field(default_factory=_now)

    @property
    def невыполненные(self) -> list[Проверка]:
        return [п for п in self.проверки if not п.выполнено]

    def текст(self) -> str:
        """Отказ словами: что просили, почему нельзя и как пройти законно."""
        куда_словами = STAGE_LABELS.get(self.куда, self.куда)
        откуда_словами = STAGE_LABELS.get(self.откуда, self.откуда)
        строки = [
            f"Переход «{откуда_словами}» → «{куда_словами}» не выполнен: {self.причина}."
        ]
        if self.причина == НЕТ_СТАДИИ:
            строки.append("")
            строки.append(f"Стадии задачи: {', '.join(STAGES)}.")
        elif self.причина == НЕТ_СТРЕЛКИ:
            строки.append("")
            строки.append(
                f"Из стадии «{откуда_словами}» ведут только переходы: "
                + (", ".join(self.разрешено) or "никуда — задача завершена") + "."
            )
        for проверка in self.невыполненные:
            строки.append("")
            заголовок = f"• {проверка.правило}  [условие «{проверка.код}», {проверка.уровень}]"
            строки.append(заголовок)
            if проверка.почему:
                строки.append(f"  Почему так: {проверка.почему}")
            if проверка.видно:
                строки.append(f"  Сейчас в задаче: {проверка.видно}.")
            if проверка.вместо:
                строки.append(f"  Чтобы открыть переход: {проверка.вместо}.")
        if len(self.маршрут) > 2:
            # Маршрут в одну стрелку показывать незачем: он совпадает с самой
            # просьбой, и строка «законный маршрут: планирование → исполнение»
            # только повторяет то, в чём уже отказано.
            строки.append("")
            строки.append(
                "Законный маршрут до цели: "
                + " → ".join(STAGE_LABELS.get(с, с) for с in self.маршрут) + "."
            )
        if self.следующий:
            стадия = self.следующий.get("стадия", "")
            словами = STAGE_LABELS.get(стадия, стадия)
            если_можно = self.следующий.get("можно")
            строка = f"Ближайший шаг маршрута — «{словами}» ({стадия})"
            не_хватает = self.следующий.get("чего_не_хватает") or []
            if если_можно:
                строки.append(строка + ": он сейчас открыт.")
            elif не_хватает:
                первое = не_хватает[0]
                строки.append(строка + f", но и он закрыт: {первое.get('видно', '')}.")
                if первое.get("вместо"):
                    строки.append(f"  Чтобы открыть его: {первое['вместо']}.")
            else:
                строки.append(строка + ".")
        строки.append("")
        строки.append(
            "Стадию задачи меняет код по условию, а не формулировка ответа: "
            "даже если в ответе написано «готово», состояние останется прежним, "
            "пока условие не выполнено."
        )
        return "\n".join(строки)

    def to_dict(self) -> dict[str, Any]:
        return {
            "откуда": self.откуда, "куда": self.куда, "кто": self.кто,
            "причина": self.причина, "когда": self.когда,
            "разрешено": list(self.разрешено), "маршрут": list(self.маршрут),
            "следующий": dict(self.следующий),
            "проверки": [п.to_dict() for п in self.проверки],
            "невыполненные": [п.код for п in self.невыполненные],
            "текст": self.текст(),
        }


@dataclass
class Вердикт:
    """Можно ли перейти, и если нет — почему."""

    можно: bool
    откуда: str
    куда: str
    кто: str = ЧЕЛОВЕК
    проверки: list[Проверка] = field(default_factory=list)
    отказ: ОтказПерехода | None = None
    выполнен: bool = False        # был ли переход сделан на самом деле

    @property
    def причина(self) -> str:
        if self.можно:
            return "переход разрешён"
        return self.отказ.причина if self.отказ else НЕ_ВЫПОЛНЕНО

    def to_dict(self) -> dict[str, Any]:
        return {
            "можно": self.можно, "откуда": self.откуда, "куда": self.куда,
            "кто": self.кто, "выполнен": self.выполнен, "причина": self.причина,
            "проверки": [п.to_dict() for п in self.проверки],
            "отказ": self.отказ.to_dict() if self.отказ else None,
        }


class ПереходОтклонён(RuntimeError):
    """Исключение с прикреплённым отказом: интерфейсы показывают его по-своему."""

    def __init__(self, отказ: ОтказПерехода) -> None:
        super().__init__(отказ.текст())
        self.отказ = отказ


# --- ворота -------------------------------------------------------------------

class Ворота:
    """Единственное место, где стадия задачи меняется.

    Условия берутся вызовом, а не снимком: пользователь может добавить условие
    посреди работы, и следующий же переход должен его увидеть.
    """

    def __init__(self, условия: Callable[[], list[Условие]] | None = None) -> None:
        self._условия = условия or (lambda: list(БАЗОВЫЕ))

    def условия(self) -> list[Условие]:
        return self._условия()

    def для(self, откуда: str, куда: str) -> list[Условие]:
        """Условия, применимые к конкретному переходу."""
        return [у for у in self.условия() if у.подходит(откуда, куда)]

    @staticmethod
    def маршрут(откуда: str, куда: str) -> list[str]:
        """Кратчайший законный маршрут по графу переходов; пустой — если пути нет."""
        if откуда == куда:
            return [откуда]
        очередь = deque([[откуда]])
        видели = {откуда}
        while очередь:
            путь = очередь.popleft()
            for следующая in TRANSITIONS.get(путь[-1], ()):
                if следующая in видели:
                    continue
                if следующая == куда:
                    return путь + [следующая]
                видели.add(следующая)
                очередь.append(путь + [следующая])
        return []

    def проверить(self, state: TaskState, куда: str, кто: str = ЧЕЛОВЕК) -> Вердикт:
        """Выносит вердикт, ничего не меняя. Этим пользуются интерфейсы."""
        откуда = state.stage
        if куда not in STAGES:
            отказ = ОтказПерехода(откуда=откуда, куда=куда, кто=кто, причина=НЕТ_СТАДИИ,
                                  разрешено=list(state.allowed()))
            return Вердикт(False, откуда, куда, кто, отказ=отказ)
        if not state.can_go(куда):
            маршрут = self.маршрут(откуда, куда)
            отказ = ОтказПерехода(
                откуда=откуда, куда=куда, кто=кто, причина=НЕТ_СТРЕЛКИ,
                разрешено=list(state.allowed()), маршрут=маршрут,
                следующий=self._следующий_шаг(state, маршрут),
            )
            return Вердикт(False, откуда, куда, кто, отказ=отказ)

        проверки: list[Проверка] = []
        for условие in self.для(откуда, куда):
            выполнено, видно = условие.проверить(state)
            проверки.append(Проверка(
                код=условие.код, правило=условие.правило, выполнено=выполнено,
                видно=видно, почему=условие.почему, вместо=условие.вместо,
                уровень=условие.уровень,
            ))
        невыполненные = [п for п in проверки if not п.выполнено]
        if невыполненные:
            отказ = ОтказПерехода(
                откуда=откуда, куда=куда, кто=кто, причина=НЕ_ВЫПОЛНЕНО,
                проверки=проверки, разрешено=list(state.allowed()),
                маршрут=self.маршрут(откуда, куда),
            )
            return Вердикт(False, откуда, куда, кто, проверки=проверки, отказ=отказ)
        return Вердикт(True, откуда, куда, кто, проверки=проверки)

    def перевести(self, state: TaskState, куда: str, кто: str = ЧЕЛОВЕК,
                  note: str = "") -> Вердикт:
        """Проверяет и, если можно, переводит. Попытка записывается в любом случае."""
        вердикт = self.проверить(state, куда, кто)
        if not вердикт.можно:
            state.записать_отказ(вердикт.отказ.to_dict())
            return вердикт
        пометка = note or f"переход запросил: {кто}"
        state.transition(куда, пометка)
        state.записать_условия(куда, [п.to_dict() for п in вердикт.проверки], кто)
        вердикт.выполнен = True
        return вердикт

    def _следующий_шаг(self, state: TaskState, маршрут: list[str]) -> dict[str, Any]:
        """Вердикт по ближайшему шагу маршрута — он идёт в текст отказа.

        Рекурсии здесь нет: ближайший шаг всегда соседняя стадия, и её проверка
        до этой ветки уже не доходит.
        """
        if len(маршрут) < 2:
            return {}
        следующая = маршрут[1]
        вердикт = self.проверить(state, следующая, КОД)
        return {
            "стадия": следующая,
            "можно": вердикт.можно,
            "чего_не_хватает": [
                {"код": п.код, "видно": п.видно, "вместо": п.вместо}
                for п in вердикт.проверки if not п.выполнено
            ],
        }

    def обзор(self, state: TaskState) -> list[dict[str, Any]]:
        """Все четыре стадии с вердиктом по каждой — то, что рисует страница.

        Интерфейс показывает и запертые переходы, а не прячет их: спрятанная
        кнопка ничему не учит, а запертая с причиной объясняет жизненный цикл.
        """
        итог: list[dict[str, Any]] = []
        for стадия in STAGES:
            if стадия == state.stage:
                итог.append({
                    "стадия": стадия, "словами": STAGE_LABELS.get(стадия, стадия),
                    "текущая": True, "можно": False, "причина": "это текущая стадия",
                    "проверки": [], "маршрут": [],
                })
                continue
            вердикт = self.проверить(state, стадия)
            итог.append({
                "стадия": стадия,
                "словами": STAGE_LABELS.get(стадия, стадия),
                "текущая": False,
                "можно": вердикт.можно,
                "причина": ("переход открыт" if вердикт.можно
                            else (вердикт.отказ.причина if вердикт.отказ else "")),
                "чего_не_хватает": [
                    {"код": п.код, "видно": п.видно, "вместо": п.вместо}
                    for п in вердикт.проверки if not п.выполнено
                ],
                "проверки": [п.to_dict() for п in вердикт.проверки],
                "маршрут": self.маршрут(state.stage, стадия),
            })
        return итог


# --- канал «модель просит переход» --------------------------------------------

def просьба(text: str) -> str:
    """Какую стадию просит модель отдельной строкой «ПЕРЕХОД: <стадия>».

    Маркер намеренно отделён от текста ответа: «я считаю задачу готовой» — это
    мнение, а строка с маркером — обращение к коду, и разбирает её код.
    """
    найдено = _МАРКЕР.findall(text or "")
    if not найдено:
        return ""
    # Если модель попросила несколько раз, берём последнюю просьбу: она
    # относится к концу ответа, то есть к итогу работы.
    return найдено[-1].strip().lower()


def убрать_маркер(text: str) -> str:
    """Убирает строку-просьбу из ответа: наружу идёт итог, а не служебная строка."""
    без_маркера = _МАРКЕР.sub("", text or "")
    return re.sub(r"\n{3,}", "\n\n", без_маркера).strip()
